#![forbid(unsafe_code)]
//! backend-rust: generates 100% safe Rust from the unified IR.
//!
//! Two codegen modes:
//! - **dynamic** (JavaScript / TypeScript / Python): every value is
//!   `transpiler_rt::Value`; every local is `Rt<Value>` so closures share
//!   state exactly like the source language.
//! - **typed** (Go / Java / Kotlin): primitives map to `i64/f64/bool/String`,
//!   structs/classes to `Rt<Struct>`, arrays to `Rt<Vec<T>>`, maps to
//!   `Rt<HashMap<K,V>>`.
//!
//! Every generated module starts with `#![forbid(unsafe_code)]`.

use std::collections::{HashMap as Map, HashSet as Set};
use std::fmt::Write as _;

use transpiler_core::ir::*;
use transpiler_core::names::{rust_ident, rust_string_body, rust_type_name};

pub struct Options {
    /// module name used in `mod` statements and file naming
    pub module_name: String,
}

pub fn default_options() -> Options {
    Options { module_name: "generated".into() }
}

pub fn generate(module: &Module) -> String {
    generate_with(module, default_options())
}

pub fn generate_with(module: &Module, opts: Options) -> String {
    let mut g = Gen {
        module,
        dynamic: module.lang.dynamic(),
        out: String::new(),
        indent: 0,
        scope: Scope::default(),
        globals: Set::new(),
        classes: Map::new(),
        classes_order: vec![],
        functions: Set::new(),
        needs_entries: false,
        needs_indices: false,
        defer_stack: vec![],
    };
    g.collect_symbols();
    g.gen();
    let mut header = String::new();
    let _ = writeln!(header, "#![forbid(unsafe_code)]");
    let _ = writeln!(header, "// generated by hexa2rust from {} source", module.lang.name());
    let _ = writeln!(header, "#![allow(dead_code, unused_mut, unused_variables, unused_parens, unused_imports, non_snake_case, non_camel_case_types, unused_assignments, unreachable_code, clippy::all)]");
    let _ = writeln!(header, "use transpiler_rt::prelude::*;");
    if g.needs_indices {
        let _ = writeln!(header, "use transpiler_rt::__indices__;");
    }
    if g.needs_entries {
        let _ = writeln!(header, "use transpiler_rt::__entries__;");
    }
    format!("{}\n{}", header, g.out)
}

#[derive(Default, Clone)]
struct Scope {
    locals: Map<String, Ty>,
    in_closure: bool,
    params: Set<String>,
    is_method: bool,
    is_ctor: bool,
    /// all cell-wrapped locals visible here (own + enclosing functions)
    cell_locals: Set<String>,
    class_of: Option<String>,
    parent_of: Option<String>,
    ret_ty: Option<Ty>,
}

struct Gen<'a> {
    module: &'a Module,
    dynamic: bool,
    out: String,
    indent: usize,
    scope: Scope,
    globals: Set<String>,
    classes: Map<String, &'a ClassDecl>,
    classes_order: Vec<String>,
    functions: Set<String>,
    needs_indices: bool,
    needs_entries: bool,
    defer_stack: Vec<Vec<String>>,
}

impl<'a> Gen<'a> {
    fn collect_symbols(&mut self) {
        let decls: Vec<&Decl> = self.module.decls.iter().collect();
        for d in &decls {
            match d {
                Decl::Global(g) => {
                    self.globals.insert(g.name.clone());
                }
                Decl::Function(f) => {
                    self.functions.insert(f.name.clone());
                }
                Decl::Class(c) => {
                    if !self.classes.contains_key(&c.name) {
                        self.classes_order.push(c.name.clone());
                    }
                    self.classes.insert(c.name.clone(), c);
                }
                Decl::TypeAlias { .. } => {}
            }
        }
    }

    fn w(&mut self, s: &str) {
        for line in s.split('\n') {
            if line.is_empty() {
                self.out.push('\n');
            } else {
                for _ in 0..self.indent {
                    self.out.push_str("    ");
                }
                self.out.push_str(line);
                self.out.push('\n');
            }
        }
    }

    fn gen(&mut self) {
        // classes first (Rust items order-independent)
        let classes: Vec<&ClassDecl> = self
            .classes_order
            .iter()
            .filter_map(|n| self.classes.get(n).copied())
            .collect();
        for c in &classes {
            if c.kind == ClassKind::Interface {
                continue; // no runtime for interfaces
            }
            if self.dynamic {
                self.gen_dynamic_class(c);
            } else {
                self.gen_typed_class(c);
            }
        }
        // globals
        for d in &self.module.decls {
            if let Decl::Global(g) = d {
                self.gen_global(g);
            }
        }
        // functions
        let mut fns: Vec<&FunctionDecl> = Vec::new();
        for d in &self.module.decls {
            if let Decl::Function(f) = d {
                if !f.is_ctor && f.name != "__main__" {
                    fns.push(f);
                }
            }
        }

        for f in &fns {
            if self.dynamic {
                self.gen_dynamic_function(f, None);
            } else {
                self.gen_typed_function(f, None);
            }
        }
        // module init + main
        let has_globals = self
            .module
            .decls
            .iter()
            .any(|d| matches!(d, Decl::Global(g) if g.init.is_some()));
        let main_fn = self
            .module
            .decls
            .iter()
            .find(|d| matches!(d, Decl::Function(f) if f.name == "__main__"));
        if has_globals || main_fn.is_some() {
            self.w("pub fn __init_module__() {");
            self.indent += 1;
            if has_globals {
                for d in &self.module.decls {
                    if let Decl::Global(g) = d {
                        if let Some(init) = &g.init {
                            let val = self.expr(init);
                            self.set_global(g, &val);
                        }
                    }
                }
            }
            if let Some(Decl::Function(f)) = main_fn {
                let body = f.body.clone();
                self.gen_block(&body);
            }
            self.indent -= 1;
            self.w("}");
        }
    }

    fn set_global(&mut self, g: &GlobalDecl, val: &str) {
        let id = rust_ident(&g.name);
        if self.dynamic {
            let _ = format!("set_{}({});", id, val);
            self.w(&format!("set_{}({});", id, val));
        } else {
            self.w(&format!("{}__set({});", id, val));
        }
    }

    fn gen_global(&mut self, g: &GlobalDecl) {
        let id = rust_ident(&g.name);
        if self.dynamic {
            self.w(&format!(
                "thread_local! {{ static {}_CELL: RefCell<Value> = RefCell::new(Value::Undefined); }}",
                id
            ));
            self.w(&format!(
                "pub fn {}() -> Value {{ {}_CELL.with(|c| c.borrow().clone()) }}",
                id, id
            ));
            self.w(&format!(
                "pub fn set_{}(v: Value) {{ {}_CELL.with(|c| *c.borrow_mut() = v); }}",
                id, id
            ));
        } else {
            let ty = self.ty(&g.ty);
            let default = default_value(&g.ty);
            self.w(&format!(
                "thread_local! {{ static {0}_CELL: RefCell<{1}> = RefCell::new({2}); }}",
                id, ty, default
            ));
            self.w(&format!(
                "pub fn {0}() -> {1} {{ {0}_CELL.with(|c| c.borrow().clone()) }}",
                id, ty
            ));
            self.w(&format!(
                "pub fn {0}__set(v: {1}) {{ {0}_CELL.with(|c| *c.borrow_mut() = v); }}",
                id, ty
            ));
        }
    }

    // ------------------------------------------------------------------
    // dynamic classes
    // ------------------------------------------------------------------
    fn gen_dynamic_class(&mut self, c: &ClassDecl) {
        let cname = &c.name;
        // constructor: fn C_new(args...) -> Value creating an object,
        // running field inits and installing methods.
        if let Some(ctor) = &c.ctor {
            let mut f = ctor.clone();
            f.name = format!("{}_new", cname);
            self.gen_dynamic_function(&f, Some(cname.to_string()));
        } else {
            // default ctor
            let mut f = FunctionDecl::new(&format!("{}_new", cname), vec![], Ty::Any, vec![]);
            self.gen_dynamic_function(&f, Some(cname.to_string()));
        }
        // class object: fn __class_C() -> Value with statics + `new`
        let mut parts = vec![format!("(\"__name__\", Value::Str(\"{}\".into()))", cname)];
        for f in &c.methods {
            if f.is_static {
                // static methods as plain fields on the class object
                parts.push(format!(
                    "(\"{}\", Value::Func(Rc::new({}_{})))",
                    f.name, cname, f.name
                ));
            }
        }
        for fld in &c.fields {
            if fld.is_static {
                let init = match &fld.init {
                    Some(e) => self.expr(e),
                    None => "Value::Undefined".to_string(),
                };
                parts.push(format!("(\"{}\", {})", fld.name, init));
            }
        }
        parts.push(format!(
            "(\"new\", Value::Func(Rc::new({}_new)))",
            cname
        ));
        self.w(&format!(
            "pub fn __class_{}() -> Value {{ obj_new(vec![{}]) }}",
            cname,
            parts.join(", ")
        ));
        // enum-like: expose fields directly as a class object too
        if c.kind == ClassKind::Enum {
            let items: Vec<String> = c
                .fields
                .iter()
                .map(|f| {
                    format!(
                        "\"{}\", {}",
                        f.name,
                        f.init.as_ref().map(|e| self.expr(e)).unwrap_or_else(|| "Value::Int(0)".into())
                    )
                })
                .collect();
            let _ = items;
        }
        // method install helper: fn C__install_methods(obj: &Value)
        let methods: Vec<&FunctionDecl> = c.methods.iter().filter(|m| !m.is_static).collect();
        self.w(&format!(
            "pub fn {}__install_methods(o: &Value) {{",
            cname
        ));
        self.indent += 1;
        for m in &methods {
            self.w(&format!(
                "Value::set_field(o, \"{}\", Value::Func(Rc::new({}_{})));",
                m.name, cname, m.name
            ));
        }
        if let Some(parent) = &c.extends {
            self.w(&format!("{}__install_methods(o);", rust_ident(parent)));
        }
        self.indent -= 1;
        self.w("}");
        // emit method functions
        for m in &c.methods {
            let mut f = m.clone();
            f.name = format!("{}_{}", cname, m.name);
            // method calling convention: args[0] is this
            self.gen_dynamic_function(&f, Some(cname.to_string()));
        }
        if let Some(ctor) = &c.ctor {
            let _ = ctor;
        }
    }

    // ------------------------------------------------------------------
    // typed classes
    // ------------------------------------------------------------------
    fn gen_typed_class(&mut self, c: &ClassDecl) {
        if c.kind == ClassKind::Interface {
            return;
        }
        let cname = rust_type_name(&c.name);
        // struct
        self.w(&format!("#[derive(Clone, Debug)]"));
        self.w(&format!("pub struct {} {{", cname));
        self.indent += 1;
        let all_fields = self.all_fields(c);
        for (fname, fty) in &all_fields {
            let ty = self.ty(fty);
            self.w(&format!("pub {}: {},", rust_ident(fname), ty));
        }
        self.indent -= 1;
        self.w("}");
        // constructor
        self.w(&format!("impl {} {{", cname));
        self.indent += 1;
        self.w(&format!(
            "pub fn new() -> Self {{ {} {{ {} }} }}",
            cname,
            all_fields
                .iter()
                .map(|(n, t)| format!("{}: {}", rust_ident(n), default_value(t)))
                .collect::<Vec<_>>()
                .join(", ")
        ));
        self.indent -= 1;
        self.w("}");
        // methods as impl (taking &Rt<Self>) — plain methods with &self when
        // they do not assign fields; simpler & uniform: all take &Rt<Self>
        let c_ptr = format!("Rt<{}>", cname);
        self.w(&format!("impl {} {{", cname));
        self.indent += 1;
        let mut has_method = false;
        for m in &c.methods {
            if m.is_static {
                continue;
            }
            has_method = true;
            let params: Vec<String> = m
                .params
                .iter()
                .map(|p| format!("{}: {}", rust_ident(&p.name), self.ty(&p.ty)))
                .collect();
            let ret = self.ty(&m.ret);
            let ret_s: String = if matches!(m.ret, Ty::Void) { "".into() } else { format!(" -> {}", ret) };
            let mname = format!("m_{}", rust_ident(&m.name));
            let params_full = if params.is_empty() {
                format!("this: &{}", c_ptr)
            } else {
                format!("this: &{}, {}", c_ptr, params.join(", "))
            };
            self.w(&format!("pub fn {}({}){} {{", mname, params_full, ret_s));
            self.indent += 1;
            let mut scope = Scope::default();
            for p in &m.params {
                scope.locals.insert(p.name.clone(), p.ty.clone());
                scope.params.insert(p.name.clone());
            }
            scope.is_method = true;
            scope.class_of = Some(c.name.clone());
            let saved = std::mem::replace(&mut self.scope, scope);
            let body = m.body.clone();
            self.gen_block_ret(&body, &m.ret);
            self.scope = saved;
            self.indent -= 1;
            self.w("}");
        }
        self.indent -= 1;
        self.w("}");
        if !has_method {
            // keep an empty impl for the struct even without methods
        }
        // static methods as free functions
        for m in &c.methods {
            if !m.is_static {
                continue;
            }
            let mut f = m.clone();
            f.name = format!("{}_{}", c.name, m.name);
            self.gen_typed_function(&f, None);
        }
    }

    fn all_fields(&self, c: &ClassDecl) -> Vec<(String, Ty)> {
        let mut out = Vec::new();
        // flatten parent fields first
        if let Some(parent) = &c.extends {
            if let Some(pc) = self.classes.get(parent) {
                out.extend(self.all_fields(pc));
            }
        }
        for f in &c.fields {
            if !f.is_static {
                out.push((f.name.clone(), f.ty.clone()));
            }
        }
        out
    }

    // ------------------------------------------------------------------
    // functions
    // ------------------------------------------------------------------
    fn gen_dynamic_function(&mut self, f: &FunctionDecl, class_of: Option<String>) {
        let fname = rust_ident(&f.name);
        let mut scope = Scope::default();
        let is_method = class_of.is_some();
        let is_new = f.name.ends_with("_new");
        let this_param = is_method && !is_new;
        self.w(&format!("pub fn {}(args: Vec<Value>) -> Value {{", fname));
        self.indent += 1;
        self.w("let mut args = args;");
        if this_param {
            scope.locals.insert("this".into(), Ty::Any);
            scope.cell_locals.insert("this".into());
            self.w("let this: Rt<Value> = rt(args.get(0).cloned().unwrap_or(Value::Undefined));");
            // Python-style methods: first parameter (self) aliases `this`
            if let Some(first) = f.params.first() {
                if first.name == "self" {
                    let pid = rust_ident(&first.name);
                    scope.locals.insert(first.name.clone(), Ty::Any);
                    scope.cell_locals.insert(first.name.clone());
                    self.w(&format!("let {}: Rt<Value> = this.clone();", pid));
                }
            }
        }
        let mut idx = if this_param { 1 } else { 0 };
        let skip_first = this_param && f.params.first().map_or(false, |p| p.name == "self");
        for p in f.params.iter().skip(if skip_first { 1 } else { 0 }) {
            scope.locals.insert(p.name.clone(), Ty::Any);
            scope.cell_locals.insert(p.name.clone());
            if p.default.is_some() {
                let d = self.expr(p.default.as_ref().unwrap());
                self.w(&format!(
                    "let {0}: Rt<Value> = rt(args.get({1}).cloned().unwrap_or_else(|| {2}));",
                    rust_ident(&p.name),
                    idx,
                    d
                ));
            } else if p.variadic {
                self.w(&format!(
                    "let {0}: Rt<Value> = rt(Value::array(args.split_off({1})));",
                    rust_ident(&p.name),
                    idx
                ));
                idx += 1;
                continue;
            } else {
                self.w(&format!(
                    "let {0}: Rt<Value> = rt(args.get({1}).cloned().unwrap_or(Value::Undefined));",
                    rust_ident(&p.name),
                    idx
                ));
            }
            idx += 1;
        }
        scope.params = f.params.iter().map(|p| p.name.clone()).collect();
        scope.is_method = is_method;
        scope.is_ctor = f.is_ctor || is_new;
        scope.class_of = class_of.clone();
        if let Some(cname) = &class_of {
            if let Some(c) = self.classes.get(cname.as_str()) {
                if let Some(p) = &c.extends {
                    scope.parent_of = Some(p.clone());
                }
            }
        }
        let saved = std::mem::replace(&mut self.scope, scope);
        self.defer_stack.push(vec![]);
        let body = f.body.clone();
        if self.scope.is_ctor {
            if let Some(cname) = &class_of {
                self.w("let this: Rt<Value> = rt(Value::object(Obj::new()));");
                self.w(&format!(
                    "Value::set_field(&this.borrow(), \"__class__\", Value::Str(\"{}\".into()));",
                    cname
                ));
                // run field initializers first
                if let Some(c) = self.classes.get(cname.as_str()) {
                    for fld in &c.fields {
                        if !fld.is_static {
                            let init = match &fld.init {
                                Some(e) => self.expr(e),
                                None => "Value::Undefined".into(),
                            };
                            self.w(&format!(
                                "Value::set_field(&this.borrow(), \"{}\", {});",
                                fld.name, init
                            ));
                        }
                    }
                }
            }
        }
        self.gen_block(&body);
        if self.scope.is_ctor {
            if let Some(cname) = &class_of {
                self.w(&format!("{}__install_methods(&this.borrow());", rust_ident(cname)));
                self.w("return this.borrow().clone();");
            }
        }
        // deferred calls at function exit
        if let Some(defers) = self.defer_stack.pop() {
            for d in defers.iter().rev() {
                self.w(d);
            }
        }
        self.w("Value::Undefined");
        self.indent -= 1;
        self.w("}");
        self.scope = saved;
    }

    fn gen_typed_function(&mut self, f: &FunctionDecl, _class_of: Option<String>) {
        let fname = rust_ident(&f.name);
        let params: Vec<String> = f
            .params
            .iter()
            .map(|p| format!("{}: {}", rust_ident(&p.name), self.ty(&p.ty)))
            .collect();
        let ret = self.ty(&f.ret);
        let ret_s: String = if matches!(f.ret, Ty::Void) { "".into() } else { format!(" -> {}", ret) };
        self.w(&format!("pub fn {}({}){} {{", fname, params.join(", "), ret_s));
        self.indent += 1;
        let mut scope = Scope::default();
        for p in &f.params {
            scope.locals.insert(p.name.clone(), p.ty.clone());
            scope.params.insert(p.name.clone());
        }
        scope.ret_ty = Some(f.ret.clone());
        let saved = std::mem::replace(&mut self.scope, scope);
        self.defer_stack.push(vec![]);
        let body = f.body.clone();
        self.gen_block_ret(&body, &f.ret);
        if let Some(defers) = self.defer_stack.pop() {
            for d in defers.iter().rev() {
                self.w(d);
            }
        }
        self.scope = saved;
        self.indent -= 1;
        self.w("}");
    }

    // ------------------------------------------------------------------
    // statements
    // ------------------------------------------------------------------
    fn gen_block(&mut self, b: &Block) {
        self.gen_block_ret(b, &Ty::Any);
    }

    fn gen_block_ret(&mut self, b: &Block, ret_ty: &Ty) {
        let returns_value = !matches!(ret_ty, Ty::Void | Ty::Any);
        for (i, s) in b.iter().enumerate() {
            let last = i == b.len() - 1;
            if last && returns_value {
                if let Stmt::Return(Some(e)) = s {
                    let v = if self.dynamic {
                        self.expr(e)
                    } else if self.is_val_expr(e) {
                        let vv = self.to_value(e);
                        self.from_value(&vv, ret_ty)
                    } else {
                        self.expr_typed(e, ret_ty)
                    };
                    self.w(&format!("return {};", v));
                    continue;
                }
            }
            self.stmt(s);
        }
    }

    fn stmt(&mut self, s: &Stmt) {
        match s {
            Stmt::Pass | Stmt::Comment(_) => {}
            Stmt::Local { name, ty, init, mutable } => {
                let id = rust_ident(name);
                if self.dynamic {
                    let val = init
                        .as_ref()
                        .map(|e| self.expr(e))
                        .unwrap_or_else(|| "Value::Undefined".into());
                    self.w(&format!("let {}{}: Rt<Value> = rt({});", if *mutable { "mut " } else { "" }, id, val));
                    self.scope.locals.insert(name.clone(), Ty::Any);
                    self.scope.cell_locals.insert(name.clone());
                } else {
                    self.scope.locals.insert(name.clone(), ty.clone());
                    match ty {
                        Ty::Any => {
                            // untyped local: infer class constructor calls
                            let inferred = match init {
                                Some(Expr::Call { callee, .. }) => match &**callee {
                                    Expr::Ident(n) if self.classes.contains_key(n) => {
                                        Some(Ty::class(n))
                                    }
                                    _ => None,
                                },
                                _ => None,
                            };
                            match inferred {
                                Some(cty) => {
                                    let val = init
                                        .as_ref()
                                        .map(|e| self.expr_typed(e, &cty))
                                        .unwrap_or_else(|| default_value(&cty));
                                    self.w(&format!(
                                        "let {}{}: {} = {};",
                                        if *mutable { "mut " } else { "" },
                                        id,
                                        self.ty(&cty),
                                        val
                                    ));
                                    self.scope.locals.insert(name.clone(), cty);
                                }
                                None => {
                                    let val = init
                                        .as_ref()
                                        .map(|e| self.to_value(e))
                                        .unwrap_or_else(|| "Value::Undefined".into());
                                    self.w(&format!("let {}{}: Rt<Value> = rt({});", if *mutable { "mut " } else { "" }, id, val));
                                }
                            }
                        }
                        _ => {
                            let val = init
                                .as_ref()
                                .map(|e| self.expr_typed(e, ty))
                                .unwrap_or_else(|| default_value(ty));
                            let t = self.ty(ty);
                            self.w(&format!("let {}{}: {} = {};", if *mutable { "mut " } else { "" }, id, t, val));
                        }
                    }
                }
            }
            Stmt::Assign { target, op, value } => {
                self.assign(target, *op, value);
            }
            Stmt::Expr(e) => {
                if self.dynamic {
                    let v = self.expr(e);
                    self.w(&format!("let _ = {};", v));
                } else {
                    match e {
                        Expr::Call { .. } | Expr::Method { .. } => {
                            let v = self.expr_typed(e, &Ty::Any);
                            self.w(&format!("let _ = {};", v));
                        }
                        Expr::AssignExpr { target, op, value } => {
                            self.assign(target, *op, value);
                        }
                        Expr::Post { .. } | Expr::Unary { op: UnOp::PreInc | UnOp::PreDec, .. } => {
                            let v = self.expr_typed(e, &Ty::Any);
                            self.w(&format!("let _ = {};", v));
                        }
                        _ => {
                            let v = self.expr(e);
                            self.w(&format!("let _ = {};", v));
                        }
                    }
                }
            }
            Stmt::If { cond, then, els } => {
                let c = self.cond(cond);
                self.w(&format!("if {} {{", c));
                self.indent += 1;
                self.gen_block(then);
                self.indent -= 1;
                if !els.is_empty() {
                    self.w("} else {");
                    self.indent += 1;
                    self.gen_block(els);
                    self.indent -= 1;
                }
                self.w("}");
            }
            Stmt::While { cond, body } => {
                let c = self.cond(cond);
                self.w(&format!("loop {{ if !({}) {{ break; }}", c));
                self.indent += 1;
                self.gen_block(body);
                self.indent -= 1;
                self.w("}");
            }
            Stmt::For { init, cond, step, body } => {
                for s in init {
                    self.stmt(s);
                }
                let c = cond
                    .as_ref()
                    .map(|e| self.cond(e))
                    .unwrap_or_else(|| "true".into());
                self.w(&format!("loop {{ if !({}) {{ break; }}", c));
                self.indent += 1;
                self.gen_block(body);
                for s in step {
                    self.stmt(s);
                }
                self.indent -= 1;
                self.w("}");
            }
            Stmt::ForEach { var, var2, var_ty, iter, body } => {
                self.gen_foreach(var, var2.as_deref(), var_ty, iter, body);
            }
            Stmt::Return(v) => {
                // emit deferred calls before returning
                if let Some(defers) = self.defer_stack.last().cloned() {
                    if !defers.is_empty() {
                        for d in defers.iter().rev() {
                            self.w(d);
                        }
                    }
                }
                match v {
                    Some(e) => {
                        if self.dynamic {
                            let val = self.expr(e);
                            self.w(&format!("return {};", val));
                        } else if self.is_val_expr(e) {
                            let ret_hint = self.scope.ret_ty.clone().unwrap_or(Ty::Any);
                            let v = self.to_value(e);
                            let val = self.from_value(&v, &ret_hint);
                            self.w(&format!("return {};", val));
                        } else {
                            let ret_hint = self.scope.ret_ty.clone().unwrap_or(Ty::Any);
                            let val = self.expr_typed(e, &ret_hint);
                            self.w(&format!("return {};", val));
                        }
                    }
                    None => self.w("return;"),
                }
            }
            Stmt::Break => self.w("break;"),
            Stmt::Continue => self.w("continue;"),
            Stmt::Block(b) => {
                self.w("{");
                self.indent += 1;
                self.gen_block(b);
                self.indent -= 1;
                self.w("}");
            }
            Stmt::Match { subject, arms, default } => {
                self.gen_match(subject, arms, default.as_ref());
            }
            Stmt::Throw(e) => {
                if self.dynamic {
                    let v = self.expr(e);
                    self.w(&format!("panic!(\"{{}}\", {}.display());", v));
                } else {
                    let v = self.expr_typed(e, &Ty::Any);
                    self.w(&format!("panic!(\"{{}}\", {});", v));
                }
            }
            Stmt::Try { body, catches, finally } => {
                self.gen_try(body, catches, finally.as_ref());
            }
            Stmt::Defer(b) => {
                // record deferred code to run at scope exit
                let mut tmp = Gen {
                    module: self.module,
                    dynamic: self.dynamic,
                    out: String::new(),
                    indent: self.indent,
                    scope: self.scope.clone(),
                    globals: self.globals.clone(),
                    classes: self.classes.clone(),
                    classes_order: vec![],
                    functions: self.functions.clone(),
                    needs_indices: false,
                    needs_entries: false,
                    defer_stack: vec![],
                };
                for s in b {
                    tmp.stmt(s);
                }
                let code = std::mem::take(&mut tmp.out);
                if let Some(top) = self.defer_stack.last_mut() {
                    top.push(code);
                } else {
                    // top-level defer: run immediately after
                    self.w(&code);
                }
            }
            Stmt::Spawn(e) => {
                // cooperative single-threaded spawn: closure queued then run
                let body = match e {
                    Expr::Call { callee, args } => {
                        let c = self.expr(callee);
                        let a: Vec<String> = args.iter().map(|x| self.expr(x)).collect();
                        format!("{}(vec![{}]);", c, a.join(", "))
                    }
                    other => {
                        let c = self.expr(other);
                        format!("let _ = {};", c)
                    }
                };
                self.w("__spawn__(Value::func(move |_| {");
                self.indent += 1;
                self.w(&body);
                self.indent -= 1;
                self.w("}));");
            }
        }
    }

    fn gen_foreach(
        &mut self,
        var: &str,
        var2: Option<&str>,
        _var_ty: &Ty,
        iter: &Expr,
        body: &Block,
    ) {
        let id = rust_ident(var);
        let id2 = var2.map(rust_ident);
        if self.dynamic {
            let it = self.expr(iter);
            let items = self.widen_iter(&it);
            if let Some(id2) = &id2 {
                // Go k, v := range m — items are [k, v] pairs
                self.w(&format!("for __entry in {}.borrow().iter() {{", items));
                self.indent += 1;
                self.w(&format!(
                    "let {}: Rt<Value> = rt(Value::index_get(__entry, &Value::Int(0)));",
                    id
                ));
                self.w(&format!(
                    "let {}: Rt<Value> = rt(Value::index_get(__entry, &Value::Int(1)));",
                    id2
                ));
                self.gen_block(body);
                self.indent -= 1;
                self.w("}");
            } else {
                self.w(&format!("for __item in {}.borrow().iter() {{", items));
                self.indent += 1;
                self.w(&format!("let {}: Rt<Value> = rt(__item.clone());", id));
                self.scope.locals.insert(var.to_string(), Ty::Any);
                self.scope.cell_locals.insert(var.to_string());
                self.gen_block(body);
                self.indent -= 1;
                self.w("}");
            }
        } else {
            let it = self.expr_typed(iter, &Ty::Any);
            let val_iter = self.is_val_expr(iter);
            if val_iter {
                // Value-backed iterable (Ty::Any local): iterate like dynamic mode
                if id2.is_some() {
                    self.w(&format!(
                        "for __entry in __entries_v__({}).borrow().iter() {{",
                        it
                    ));
                    self.indent += 1;
                    self.scope.locals.insert(var.to_string(), Ty::Any);
                    self.scope.cell_locals.insert(var.to_string());
                    if let Some(v2) = var2 {
                        self.scope.locals.insert(v2.to_string(), Ty::Any);
                        self.scope.cell_locals.insert(v2.to_string());
                    }
                    self.w(&format!(
                        "let {}: Rt<Value> = rt(Value::index_get(__entry, &Value::Int(0)));",
                        id
                    ));
                    self.w(&format!(
                        "let {}: Rt<Value> = rt(Value::index_get(__entry, &Value::Int(1)));",
                        id2.unwrap()
                    ));
                    self.gen_block(body);
                    self.indent -= 1;
                    self.w("}");
                } else {
                    self.w(&format!("for __item in __iter__({}).borrow().iter() {{", it));
                    self.indent += 1;
                    self.w(&format!("let {}: Rt<Value> = rt(__item.clone());", id));
                    self.scope.locals.insert(var.to_string(), Ty::Any);
                    self.scope.cell_locals.insert(var.to_string());
                    self.gen_block(body);
                    self.indent -= 1;
                    self.w("}");
                }
            } else if id2.is_some() {
                // typed map entries
                self.w(&format!("for (__k, __v) in __entries__(&{}) {{", it));
                self.indent += 1;
                self.w(&format!("let {} = __k.clone();", id));
                self.w(&format!("let {} = __v.clone();", id2.unwrap()));
                self.gen_block(body);
                self.indent -= 1;
                self.w("}");
            } else {
                self.w(&format!("for __item in {}.borrow().iter() {{", it));
                self.indent += 1;
                self.w(&format!("let {} = __item.clone();", id));
                self.scope.locals.insert(var.to_string(), Ty::Any);
                self.gen_block(body);
                self.indent -= 1;
                self.w("}");
            }
        }
    }

    /// value-kind classification used by the typed backend
    fn kind_of(&self, t: &Ty) -> VKind {
        match t {
            Ty::Any | Ty::Named(_) | Ty::Func { .. } => VKind::Val,
            Ty::Array(_) | Ty::Map(_, _) | Ty::Option(_) | Ty::Class(_) => VKind::Ref,
            _ => VKind::Prim,
        }
    }

    /// does this expression evaluate to a dynamic `Value`?
    fn is_val_expr(&self, e: &Expr) -> bool {
        self.tv(e) == VKind::Val
    }

    fn tv(&self, e: &Expr) -> VKind {
        match e {
            Expr::Ident(n) => {
                if let Some(t) = self.scope.locals.get(n) {
                    self.kind_of(t)
                } else {
                    VKind::Unknown
                }
            }
            Expr::Paren(x) => self.tv(x),
            Expr::Unary { e, .. } | Expr::Post { e, .. } => self.tv(e),
            Expr::Binary { l, r, .. } => {
                let lk = self.tv(l);
                let rk = self.tv(r);
                if lk == VKind::Val || rk == VKind::Val {
                    VKind::Val
                } else if lk == VKind::Float || rk == VKind::Float {
                    VKind::Float
                } else {
                    VKind::Int
                }
            }
            Expr::Int(_) => VKind::Int,
            Expr::Float(_) => VKind::Float,
            Expr::Bool(_) => VKind::Bool,
            Expr::Str(_) | Expr::Char(_) | Expr::Interp { .. } => VKind::Str,
            Expr::Null | Expr::Undefined | Expr::Unit => VKind::Val,
            Expr::Range { .. } | Expr::Array(_) | Expr::Dict(_) | Expr::Object(_) => VKind::Val,
            Expr::Method { obj, .. } | Expr::Field { obj, .. } => self.tv(obj),
            Expr::Index { obj, .. } => self.tv(obj),
            Expr::Slice { obj, .. } => self.tv(obj),
            Expr::Call { callee, .. } => match &**callee {
                Expr::Ident(n) if n == "__map_has__" => VKind::Bool,
                Expr::Ident(n) if n == "__indices__" || n == "__keys__" => VKind::Val,
                _ => VKind::Unknown,
            },
            Expr::Ternary { then, els, .. } => {
                let a = self.tv(then);
                let b = self.tv(els);
                if a == VKind::Val || b == VKind::Val {
                    VKind::Val
                } else {
                    a
                }
            }
            _ => VKind::Unknown,
        }
    }

    /// produce a `Value` from a typed expression
    fn to_value(&mut self, e: &Expr) -> String {
        match self.tv(e) {
            VKind::Val => self.expr_typed(e, &Ty::Any),
            VKind::Int => format!("Value::Int({} as i64)", self.expr_typed(e, &Ty::Long)),
            VKind::Float => format!("Value::Float({} as f64)", self.expr_typed(e, &Ty::Double)),
            VKind::Bool => format!("Value::Bool({})", self.expr_typed(e, &Ty::Bool)),
            VKind::Str => {
                let s = self.expr_typed(e, &Ty::Str);
                format!("Value::Str({})", s)
            }
            VKind::Unknown | VKind::Ref | VKind::Prim => {
                let s = self.expr_typed(e, &Ty::Any);
                format!("Value::Str(format!(\"{{:?}}\", {}))", s)
            }
        }
    }

    /// convert a `Value` expression to the hinted type
    fn from_value(&self, v: &str, hint: &Ty) -> String {
        match hint {
            Ty::Int | Ty::Long | Ty::Named(_) => format!(
                "__to_int__(&{}).display().parse::<i64>().unwrap_or(0)",
                v
            ),
            Ty::Float | Ty::Double => format!("__to_float__(&{})", v),
            Ty::Bool => format!("{}.truthy()", v),
            Ty::Str => format!("__to_str__(&{}).display()", v),
            _ => v.to_string(),
        }
    }

    /// convert any iterable Value into Rt<Vec<Value>> of items
    fn widen_iter(&mut self, it: &str) -> String {
        format!("__iter__({})", it)
    }

    fn gen_match(&mut self, subject: &Expr, arms: &[MatchArm], default: Option<&Block>) {
        if self.dynamic {
            let s = self.expr(subject);
            self.w(&format!("let __subj = {};", s));
            let mut first = true;
            for arm in arms {
                let conds: Vec<String> = arm
                    .pattern
                    .iter()
                    .map(|p| {
                        let pv = self.expr(p);
                        format!("Value::eq(&__subj, &{})", pv)
                    })
                    .collect();
                let mut cond = conds.join(" || ");
                if let Some(g) = &arm.guard {
                    let gv = self.cond(g);
                    cond = format!("({}) && ({})", cond, gv);
                }
                if first {
                    self.w(&format!("if {} {{", cond));
                    first = false;
                } else {
                    self.w(&format!("}} else if {} {{", cond));
                }
                self.indent += 1;
                self.gen_block(&arm.body);
                self.indent -= 1;
            }
            if let Some(d) = default {
                if first {
                    self.indent += 1;
                    self.gen_block(d);
                    self.indent -= 1;
                } else {
                    self.w("} else {");
                    self.indent += 1;
                    self.gen_block(d);
                    self.indent -= 1;
                }
            }
            if !first {
                self.w("}");
            }
        } else {
            let s = self.expr_typed(subject, &Ty::Any);
            self.w(&format!("let __subj = {};", s));
            let mut first = true;
            for arm in arms {
                let conds: Vec<String> = arm
                    .pattern
                    .iter()
                    .map(|p| {
                        let pv = self.expr_typed(p, &Ty::Any);
                        format!("__subj == {}", pv)
                    })
                    .collect();
                let cond = conds.join(" || ");
                if first {
                    self.w(&format!("if {} {{", cond));
                    first = false;
                } else {
                    self.w(&format!("}} else if {} {{", cond));
                }
                self.indent += 1;
                self.gen_block(&arm.body);
                self.indent -= 1;
            }
            if let Some(d) = default {
                if first {
                    self.indent += 1;
                    self.gen_block(d);
                    self.indent -= 1;
                } else {
                    self.w("} else {");
                    self.indent += 1;
                    self.gen_block(d);
                    self.indent -= 1;
                }
            }
            if !first {
                self.w("}");
            }
        }
    }

    fn gen_try(&mut self, body: &Block, catches: &[CatchClause], finally: Option<&Block>) {
        // safe-Rust exceptions: generated code panics; catch via closure
        self.w("__try__(|| {");
        self.indent += 1;
        let saved = self.scope.clone();
        self.gen_block(body);
        self.scope = saved;
        self.indent -= 1;
        if catches.is_empty() {
            self.w("});");
        } else {
            let first = &catches[0];
            let var = first.var.clone().unwrap_or_else(|| "__err".into());
            self.w(&format!("}}, |{}: String| {{", rust_ident(&var)));
            self.indent += 1;
            let mut scope = self.scope.clone();
            scope
                .locals
                .insert(var.clone(), Ty::class("__Error"));
            let saved2 = std::mem::replace(&mut self.scope, scope);
            let cb = &first.body;
            self.gen_block(cb);
            self.scope = saved2;
            self.indent -= 1;
            self.w("});");
        }
        if let Some(f) = finally {
            self.gen_block(f);
        }
    }

    // ------------------------------------------------------------------
    // assignment
    // ------------------------------------------------------------------
    fn assign(&mut self, target: &Expr, op: Option<BinOp>, value: &Expr) {
        match target {
            Expr::Ident(name) => {
                let id = rust_ident(name);
                if self.dynamic {
                    let is_global = self.globals.contains(name);
                    let cur = if is_global {
                        format!("{}()", id)
                    } else {
                        format!("{}.borrow().clone()", id)
                    };
                    let rhs = self.expr(value);
                    let rhs = match op {
                        Some(o) => {
                            // compute the full result into a temp first so the
                            // place borrow never overlaps the value borrows
                            let tmp = format!("__rhs_{}", self.pos_hint());
                            let res = self.binop_value(o, &cur, &rhs);
                            self.w(&format!("let {} = {};", tmp, res));
                            tmp
                        }
                        None => rhs,
                    };
                    if is_global {
                        self.w(&format!("set_{}({});", id, rhs));
                    } else {
                        if !self.scope.locals.contains_key(name) {
                            self.w(&format!(
                                "let mut {}: Rt<Value> = rt(Value::Undefined);",
                                id
                            ));
                            self.scope.locals.insert(name.clone(), Ty::Any);
                            self.scope.cell_locals.insert(name.clone());
                        }
                        self.w(&format!("*{}.borrow_mut() = {};", id, rhs));
                    }
                } else {
                    let val_kind = self
                        .scope
                        .locals
                        .get(name)
                        .map(|t| self.kind_of(t))
                        .unwrap_or(VKind::Unknown);
                    match val_kind {
                        VKind::Val => {
                            let rhs = self.to_value(value);
                            let rhs = match op {
                                Some(o) => {
                                    let tmp = format!("__rhs_{}", self.pos_hint());
                                    let cur = format!("{}.borrow().clone()", id);
                                    let res = self.binop_value(o, &cur, &rhs);
                                    self.w(&format!("let {} = {};", tmp, res));
                                    tmp
                                }
                                None => rhs,
                            };
                            self.w(&format!("*{}.borrow_mut() = {};", id, rhs));
                        }
                        _ => {
                            let rhs = self.expr_typed(value, &Ty::Any);
                            let rhs = match op {
                                Some(o) => {
                                    let cur = format!("{}.clone()", id);
                                    self.binop_typed(o, &cur, &rhs)
                                }
                                None => rhs,
                            };
                            if self.globals.contains(name) {
                                self.w(&format!("{}__set({});", id, rhs));
                            } else {
                                self.w(&format!("{} = {};", id, rhs));
                            }
                        }
                    }
                }
            }
            Expr::Field { obj, name, .. } => {
                if self.dynamic {
                    let o = self.expr(obj);
                    let rhs = self.expr(value);
                    let rhs = match op {
                        Some(bo) => {
                            let cur = format!("Value::get_field(&{}, \"{}\")", o, name);
                            self.binop_value(bo, &cur, &rhs)
                        }
                        None => rhs,
                    };
                    self.w(&format!(
                        "Value::set_field(&{}, \"{}\", {});",
                        o,
                        name,
                        rhs
                    ));
                } else {
                    // struct field: obj.borrow_mut().field = v | obj.borrow().field
                    let o = self.expr_typed(obj, &Ty::Any);
                    let is_this = matches!(**obj, Expr::This);
                    let rhs = self.expr_typed(value, &Ty::Any);
                    let rhs = match op {
                        Some(bo) => {
                            let cur = format!("{}.borrow().{}", o, rust_ident(name));
                            self.binop_typed(bo, &cur, &rhs)
                        }
                        None => rhs,
                    };
                    if is_this {
                        // this: &Rt<Class> in typed methods
                        self.w(&format!(
                            "this.borrow_mut().{} = {};",
                            rust_ident(name),
                            rhs
                        ));
                    } else {
                        self.w(&format!(
                            "{}.borrow_mut().{} = {};",
                            o,
                            rust_ident(name),
                            rhs
                        ));
                    }
                }
            }
            Expr::Index { obj, idx } => {
                if self.dynamic {
                    let o = self.expr(obj);
                    let i = self.expr(idx);
                    let rhs = self.expr(value);
                    let rhs = match op {
                        Some(bo) => {
                            let cur = format!(
                                "Value::index_get(&{}, &{})",
                                o, i
                            );
                            self.binop_value(bo, &cur, &rhs)
                        }
                        None => rhs,
                    };
                    self.w(&format!(
                        "Value::index_set(&{}, &{}, {});",
                        o,
                        i,
                        rhs
                    ));
                } else {
                    let o = self.expr_typed(obj, &Ty::Any);
                    let i = self.expr_typed(idx, &Ty::Any);
                    let rhs = self.expr_typed(value, &Ty::Any);
                    match op {
                        Some(bo) => {
                            let cur = format!("{}.borrow()[{}].clone()", o, i);
                            let v = self.binop_typed(bo, &cur, &rhs);
                            self.w(&format!("{}.borrow_mut()[{}] = {};", o, i, v));
                        }
                        None => {
                            self.w(&format!("{}.borrow_mut()[{}] = {};", o, i, rhs));
                        }
                    }
                }
            }
            Expr::Paren(e) => self.assign(e, op, value),
            other => {
                let t = format!("{:?}", other);
                self.w(&format!("// unsupported assignment target: {}", t));
            }
        }
    }

    fn is_dynamic_local(&self, _name: &str) -> bool {
        self.dynamic
    }

    fn load(&self, id: &str) -> String {
        format!("{}.borrow().clone()", id)
    }

    fn pos_hint(&self) -> usize {
        self.out.len()
    }

    fn binop_value(&mut self, op: BinOp, l: &str, r: &str) -> String {
        match op {
            BinOp::Add => format!("Value::add(&{}, &{})", l, r),
            BinOp::Sub => format!("Value::sub(&{}, &{})", l, r),
            BinOp::Mul => format!("Value::mul(&{}, &{})", l, r),
            BinOp::Div => format!("Value::div(&{}, &{})", l, r),
            BinOp::FloorDiv => format!("Value::floor_div(&{}, &{})", l, r),
            BinOp::Mod => format!("Value::py_mod(&{}, &{})", l, r),
            BinOp::Pow => format!("Value::pow(&{}, &{})", l, r),
            _ => {
                let b = self.binop_bool(op, l, r);
                format!("Value::Bool({})", b)
            }
        }
    }

    fn binop_bool(&mut self, op: BinOp, l: &str, r: &str) -> String {
        match op {
            BinOp::Eq => format!("Value::eq(&{}, &{})", l, r),
            BinOp::Ne => format!("(!Value::eq(&{}, &{}))", l, r),
            BinOp::Lt => format!("Value::lt(&{}, &{})", l, r),
            BinOp::Le => format!("(!Value::lt(&{}, &{}))", r, l),
            BinOp::Gt => format!("Value::lt(&{}, &{})", r, l),
            BinOp::Ge => format!("(!Value::lt(&{}, &{}))", l, r),
            _ => "false".into(),
        }
    }

    fn binop_typed(&mut self, op: BinOp, l: &str, r: &str) -> String {
        match op {
            BinOp::Add => format!("({} + {})", l, r),
            BinOp::Sub => format!("({} - {})", l, r),
            BinOp::Mul => format!("({} * {})", l, r),
            BinOp::Div => format!("({} / {})", l, r),
            BinOp::FloorDiv => format!("floor_div_i64({}, {})", l, r),
            BinOp::Mod => format!("({} % {})", l, r),
            BinOp::Pow => format!("({} as i64).pow({} as u32) as f64", l, r),
            _ => format!("({} {} {})", l, op.symbol(), r),
        }
    }

    // ------------------------------------------------------------------
    // conditions
    // ------------------------------------------------------------------
    fn cond(&mut self, e: &Expr) -> String {
        if self.dynamic {
            format!("({}).truthy()", self.expr(e))
        } else if self.is_val_expr(e) {
            format!("({}).truthy()", self.expr_typed(e, &Ty::Any))
        } else {
            self.expr_typed(e, &Ty::Bool)
        }
    }

    // ------------------------------------------------------------------
    // expressions (dynamic mode -> Value)
    // ------------------------------------------------------------------
    fn expr(&mut self, e: &Expr) -> String {
        match e {
            Expr::Int(v) => format!("Value::Int({}i64)", v),
            Expr::Float(v) => format!("Value::Float({})", v),
            Expr::Str(s) => format!("Value::Str(\"{}\".into())", rust_string_body(s)),
            Expr::Char(c) => format!("Value::Str(\"{}\".into())", rust_string_body(&c.to_string())),
            Expr::Bool(b) => format!("Value::Bool({})", b),
            Expr::Null | Expr::Undefined | Expr::Unit => "Value::Undefined".into(),
            Expr::Ident(name) => self.ident_expr(name),
            Expr::This => "this.borrow().clone()".into(),
            Expr::Super => "this.borrow().clone()".into(),
            Expr::Paren(e) => self.expr(e),
            Expr::Binary { op, l, r } => {
                // short-circuit
                match op {
                    BinOp::And => format!(
                        "(if {}.truthy() {{ {} }} else {{ Value::Bool(false) }})",
                        self.expr(l),
                        self.expr(r)
                    ),
                    BinOp::Or => format!(
                        "(if {}.truthy() {{ Value::Bool(true) }} else {{ {} }})",
                        self.expr(l),
                        self.expr(r)
                    ),
                    BinOp::Nullish => format!(
                        "(if matches!({}, Value::Null | Value::Undefined) {{ {} }} else {{ {} }})",
                        self.expr(l),
                        self.expr(r),
                        self.expr(l)
                    ),
                    _ => {
                        let ls = self.expr(l);
                        let rs = self.expr(r);
                        self.binop_value(*op, &ls, &rs)
                    }
                }
            }
            Expr::Unary { op, e } => match op {
                UnOp::Not => format!("Value::Bool(!({}).truthy())", self.expr(e)),
                UnOp::Neg => format!("Value::sub(&Value::Int(0), &{})", self.expr(e)),
                UnOp::BitNot => format!("Value::Int(!({}).display().parse::<i64>().unwrap_or(0))", self.expr(e)),
                UnOp::PreInc | UnOp::PreDec => {
                    let one = if matches!(op, UnOp::PreInc) { "add" } else { "sub" };
                    match &**e {
                        Expr::Ident(n) => {
                            let id = rust_ident(n);
                            let is_global = self.globals.contains(n);
                            let load = if is_global {
                                format!("{}()", id)
                            } else {
                                format!("{}.borrow().clone()", id)
                            };
                            let tmp = format!("__rhs_{}", self.pos_hint());
                            let res = format!("Value::{}(&{}, &Value::Int(1))", one, load);
                            self.w(&format!("let {} = {};", tmp, res));
                            if is_global {
                                self.w(&format!("set_{}({});", id, tmp));
                            } else {
                                self.w(&format!("*{}.borrow_mut() = {};", id, tmp));
                            }
                            format!("{}()", id)
                        }
                        _ => "Value::Undefined".into(),
                    }
                }
            },
            Expr::Post { op, e } => {
                let one = if matches!(op, UnOp::PreInc) { "add" } else { "sub" };
                match &**e {
                    Expr::Ident(n) => {
                        let id = rust_ident(n);
                        let is_global = self.globals.contains(n);
                        let load = if is_global {
                            format!("{}()", id)
                        } else {
                            format!("{}.borrow().clone()", id)
                        };
                        let old = load.clone();
                        let tmp = format!("__rhs_{}", self.pos_hint());
                        let res = format!("Value::{}(&{}, &Value::Int(1))", one, load);
                        self.w(&format!("let {} = {};", tmp, res));
                        if is_global {
                            self.w(&format!("set_{}({});", id, tmp));
                        } else {
                            self.w(&format!("*{}.borrow_mut() = {};", id, tmp));
                        }
                        old
                    }
                    _ => "Value::Undefined".into(),
                }
            }
            Expr::Call { callee, args } => {
                // super(...) in ctor -> parent ctor merged into this
                if matches!(&**callee, Expr::Super) {
                    let a: Vec<String> = args.iter().map(|x| self.expr(x)).collect();
                    if let Some(parent) = self.scope.parent_of.clone() {
                        return format!(
                            "__merge__(&this.borrow(), &{}_new(vec![{}]))",
                            rust_ident(&parent),
                            a.join(", ")
                        );
                    }
                    return "Value::Undefined".into();
                }
                // builtin mappings
                if let Expr::Ident(name) = &**callee {
                    if let Some(v) = self.builtin_dynamic(name, args) {
                        return v;
                    }
                    // module function direct call
                    if self.functions.contains(name) {
                        let a: Vec<String> = args.iter().map(|x| self.expr(x)).collect();
                        return format!("{}(vec![{}])", rust_ident(name), a.join(", "));
                    }
                    // global holding a class object -> call its `new`
                    if self.globals.contains(name) {
                        let a: Vec<String> = args.iter().map(|x| self.expr(x)).collect();
                        return format!(
                            "Value::call(&Value::get_field(&{}(), \"new\"), vec![{}])",
                            rust_ident(name),
                            a.join(", ")
                        );
                    }
                    // class name -> class object call (Python Point(3,4), JS C(...))
                    if self.classes.contains_key(name) {
                        let a: Vec<String> = args.iter().map(|x| self.expr(x)).collect();
                        return format!(
                            "Value::call(&Value::get_field(&__class_{}(), \"new\"), vec![{}])",
                            rust_ident(name),
                            a.join(", ")
                        );
                    }
                    // plain variable holding a function
                    let a: Vec<String> = args.iter().map(|x| self.expr(x)).collect();
                    return format!(
                        "Value::call(&{}, vec![{}])",
                        self.ident_expr(name),
                        a.join(", ")
                    );
                }
                let f = self.expr(callee);
                let a: Vec<String> = args.iter().map(|x| self.expr(x)).collect();
                format!("Value::call(&{}, vec![{}])", f, a.join(", "))
            }
            Expr::Method { obj, name, args, nullsafe } => {
                // builtin methods handled inside Value::call_method
                let o = self.expr(obj);
                let mut a: Vec<String> = args.iter().map(|x| self.expr(x)).collect();
                // user-defined method on objects: this as args[0]
                if let Some(v) = self.builtin_method_dynamic(obj, name, args) {
                    return v;
                }
                let call = format!(
                    "Value::call_method(&{}, \"{}\", vec![{}])",
                    o,
                    name,
                    a.join(", ")
                );
                let _ = &mut a;
                if *nullsafe {
                    format!(
                        "(if matches!({}, Value::Null | Value::Undefined) {{ Value::Undefined }} else {{ {} }})",
                        o, call
                    )
                } else {
                    call
                }
            }
            Expr::Field { obj, name, nullsafe } => {
                let o = self.expr(obj);
                let f = format!("Value::get_field(&{}, \"{}\")", o, name);
                if *nullsafe {
                    format!(
                        "(if matches!({}, Value::Null | Value::Undefined) {{ Value::Undefined }} else {{ {} }})",
                        o, f
                    )
                } else {
                    f
                }
            }
            Expr::Index { obj, idx } => {
                let o = self.expr(obj);
                let i = self.expr(idx);
                format!("Value::index_get(&{}, &{})", o, i)
            }
            Expr::Slice { obj, lo, hi } => {
                let o = self.expr(obj);
                let lo = lo.as_ref().map(|e| self.expr(e)).unwrap_or_else(|| "Value::Int(0)".into());
                let hi = hi
                    .as_ref()
                    .map(|e| self.expr(e))
                    .unwrap_or_else(|| format!("Value::get_field(&{}, \"length\")", o));
                format!("Value::call_method(&{}, \"slice\", vec![{}, {}])", o, lo, hi)
            }
            Expr::Array(items) => {
                // inline vec build so spread works
                let mut code = String::from("Value::Array(rt({ let mut __v: Vec<Value> = Vec::new(); ");
                for it in items {
                    match it {
                        Expr::Spread(inner) => {
                            code.push_str(&format!("__v.extend(__iter__({}).borrow().iter().cloned()); ", self.expr(inner)));
                        }
                        other => {
                            code.push_str(&format!("__v.push({}); ", self.expr(other)));
                        }
                    }
                }
                code.push_str("__v }))");
                code
            }
            Expr::Dict(pairs) => {
                let entries: Vec<String> = pairs
                    .iter()
                    .map(|(k, v)| format!("({}, {})", self.expr(k), self.expr(v)))
                    .collect();
                format!("__dict_new__([{}])", entries.join(", "))
            }
            Expr::Object(fields) => {
                let mut parts = Vec::new();
                for (k, v) in fields {
                    if k == "__SPREAD__" {
                        parts.push(format!("(\"__SPREAD__\", __obj_spread__(&{}))", self.expr(v)));
                    } else {
                        parts.push(format!("(\"{}\", {})", k, self.expr(v)));
                    }
                }
                format!("obj_new(vec![{}])", parts.join(", "))
            }
            Expr::New { class, args } => {
                if self.classes.contains_key(class) {
                    let a: Vec<String> = args.iter().map(|x| self.expr(x)).collect();
                    format!("{}_new(vec![{}])", rust_ident(class), a.join(", "))
                } else {
                    let a: Vec<String> = args.iter().map(|x| self.expr(x)).collect();
                    format!(
                        "Value::call(&Value::get_field(&{}(), \"new\"), vec![{}])",
                        rust_ident(class),
                        a.join(", ")
                    )
                }
            }
            Expr::Closure { params, body, value } => {
                // closures inherit enclosing cell locals by name
                let mut inner_locals = self.scope.locals.clone();
                let mut inner_cells = self.scope.cell_locals.clone();
                for p in params {
                    inner_locals.insert(p.name.clone(), Ty::Any);
                    inner_cells.insert(p.name.clone());
                }
                let mut inner = Gen {
                    module: self.module,
                    dynamic: self.dynamic,
                    out: String::new(),
                    indent: 0,
                    scope: Scope {
                        locals: inner_locals,
                        in_closure: true,
                        params: params.iter().map(|p| p.name.clone()).collect(),
                        is_method: self.scope.is_method,
                        is_ctor: false,
                        cell_locals: inner_cells,
                        class_of: self.scope.class_of.clone(),
                        parent_of: self.scope.parent_of.clone(),
                        ret_ty: None,
                    },
                    globals: self.globals.clone(),
                    classes: self.classes.clone(),
                    classes_order: vec![],
                    functions: self.functions.clone(),
                    needs_indices: false,
                    needs_entries: false,
                    defer_stack: vec![],
                };
                for p in params {
                    let pid = rust_ident(&p.name);
                    if p.default.is_some() {
                        let d = inner.expr(p.default.as_ref().unwrap());
                        inner.w(&format!(
                            "let {0}: Rt<Value> = rt(args.get({1}).cloned().unwrap_or_else(|| {2}));",
                            pid,
                            inner_param_index(params, &p.name),
                            d
                        ));
                    } else if p.variadic {
                        inner.w(&format!(
                            "let {0}: Rt<Value> = rt(Value::array(args.split_off({1})));",
                            pid,
                            inner_param_index(params, &p.name)
                        ));
                    } else {
                        inner.w(&format!(
                            "let {0}: Rt<Value> = rt(args.get({1}).cloned().unwrap_or(Value::Undefined));",
                            pid,
                            inner_param_index(params, &p.name)
                        ));
                    }
                }
                match value {
                    Some(v) => {
                        let val = inner.expr(v);
                        inner.w(&format!("return {};", val));
                    }
                    None => {
                        inner.gen_block(body);
                        inner.w("Value::Undefined");
                    }
                }
                let code = std::mem::take(&mut inner.out);
                let body_code = code
                    .lines()
                    .map(|l| format!("    {}", l))
                    .collect::<Vec<_>>()
                    .join("\n");
                format!(
                    "Value::func(move |mut args: Vec<Value>| {{\n{}\n}})",
                    body_code
                )
            }
            Expr::Ternary { cond, then, els } => {
                let c = self.cond(cond);
                format!(
                    "(if {} {{ {} }} else {{ {} }})",
                    c,
                    self.expr(then),
                    self.expr(els)
                )
            }
            Expr::Cast { e, ty } => {
                let v = self.expr(e);
                self.cast_dynamic(&v, ty)
            }
            Expr::Interp { parts } => {
                let mut items = Vec::new();
                for p in parts {
                    match p {
                        InterpPart::Lit(s) => items.push(format!("Value::Str(\"{}\".into())", rust_string_body(s))),
                        InterpPart::E(e) => items.push(self.expr(e)),
                    }
                }
                format!("__concat__([{}])", items.join(", "))
            }
            Expr::Range { lo, hi, inclusive } => {
                let l = self.expr(lo);
                let h = self.expr(hi);
                format!(
                    "__range__(&{}, &{}, {})",
                    l,
                    h,
                    if *inclusive { "true" } else { "false" }
                )
            }
            Expr::Named { e, .. } => self.expr(e),
            Expr::Spread(e) => self.expr(e),
            Expr::Seq(items) => {
                // comma / assignment-expression sequence
                let mut last = "Value::Undefined".to_string();
                for (i, it) in items.iter().enumerate() {
                    if i + 1 == items.len() {
                        last = self.expr(it);
                    } else {
                        let v = self.expr(it);
                        self.w(&format!("let _ = {};", v));
                    }
                }
                last
            }
            Expr::Await(e) => self.expr(e),
            Expr::AssignExpr { target, op, value } => {
                // emit statement then produce new value
                self.assign(target, *op, value);
                match &**value {
                    Expr::Ident(n) => self.ident_expr(n),
                    other => self.expr(other),
                }
            }
            Expr::FuncRef(n) => format!("Value::Func(Rc::new({}))", rust_ident(n)),
        }
    }

    fn ident_expr(&mut self, name: &str) -> String {
        let id = rust_ident(name);
        if self.dynamic {
            // local (incl. this/params) -> cell; global -> getter; class -> class object
            if self.scope.locals.contains_key(name) || name == "this" {
                format!("{}.borrow().clone()", id)
            } else if self.globals.contains(name) {
                format!("{}()", id)
            } else if self.classes.contains_key(name) {
                format!("__class_{}()", rust_ident(name))
            } else {
                format!("{}.borrow().clone()", id)
            }
        } else {
            if let Some(t) = self.scope.locals.get(name) {
                match self.kind_of(t) {
                    VKind::Val => format!("{}.borrow().clone()", id),
                    _ => format!("{}.clone()", id),
                }
            } else if self.globals.contains(name) {
                format!("{}()", id)
            } else if self.scope.is_method {
                if let Some(cname) = self.scope.class_of.clone() {
                    if let Some(c) = self.classes.get(&cname) {
                        let is_field = c.fields.iter().any(|f| f.name == name)
                            || self
                                .classes
                                .get(&cname)
                                .map(|pc| self.all_fields(pc).iter().any(|(n, _)| n == name))
                                .unwrap_or(false);
                        if is_field {
                            return format!("this.borrow().{}.clone()", id);
                        }
                    }
                }
                format!("{}()", id)
            } else {
                format!("{}()", id)
            }
        }
    }

    fn is_ref_local(&self, _name: &str) -> bool {
        true
    }

    // builtin functions in dynamic mode
    fn builtin_dynamic(&mut self, name: &str, args: &[Expr]) -> Option<String> {
        let a: Vec<String> = args.iter().map(|x| self.expr(x)).collect();
        Some(match name {
            "len" | "print" | "println" | "console_log" => match name {
                "len" => format!("__len__(&{})", a.first().cloned().unwrap_or_else(|| "Value::Undefined".into())),
                "print" | "println" | "console_log" => format!("__print__(&[{}])", a.join(", ")),
                _ => unreachable!(),
            },
            "range" => {
                if args.len() == 1 {
                    let n = a[0].clone();
                    return Some(format!(
                        "__range3__(&Value::Int(0), &{}, &Value::Int(1))",
                        n
                    ));
                }
                let l = a.first().cloned().unwrap_or_else(|| "Value::Int(0)".into());
                let h = a.get(1).cloned().unwrap_or_else(|| "Value::Int(0)".into());
                let st = a.get(2).cloned().unwrap_or_else(|| "Value::Int(1)".into());
                format!("__range3__(&{}, &{}, &{})", l, h, st)
            }
            "str" => format!("__to_str__(&{})", a.first().cloned().unwrap_or_else(|| "Value::Undefined".into())),
            "int" => format!("__to_int__(&{})", a.first().cloned().unwrap_or_else(|| "Value::Undefined".into())),
            "float" => format!("__to_float__(&{})", a.first().cloned().unwrap_or_else(|| "Value::Undefined".into())),
            "bool" => format!("Value::Bool({}.truthy())", a.first().cloned().unwrap_or_else(|| "Value::Undefined".into())),
            "abs" => format!("__abs__(&{})", a.first().cloned().unwrap_or_else(|| "Value::Undefined".into())),
            "min" => format!("__min__(&[{}])", a.join(", ")),
            "max" => format!("__max__(&[{}])", a.join(", ")),
            "sum" => format!("__sum__({})", a.first().cloned().unwrap_or_else(|| "Value::array(vec![])".into())),
            "sorted" => format!("__sorted__({})", a.first().cloned().unwrap_or_else(|| "Value::array(vec![])".into())),
            "list" => format!("__to_list__(&{})", a.first().cloned().unwrap_or_else(|| "Value::Undefined".into())),
            "dict" => "Value::object(Obj::new())".into(),
            "enumerate" => format!("__enumerate__({})", a.first().cloned().unwrap_or_else(|| "Value::array(vec![])".into())),
            "isinstance" => format!("__isinstance__(&{}, &{})",
                a.first().cloned().unwrap_or_else(|| "Value::Undefined".into()),
                a.get(1).cloned().unwrap_or_else(|| "Value::Undefined".into())),
            "repr" => format!("Value::Str({}.repr())", a.first().cloned().unwrap_or_else(|| "Value::Undefined".into())),
            "__typeof__" => format!("__typeof__(&{})", a.first().cloned().unwrap_or_else(|| "Value::Undefined".into())),
            "__instanceof__" => format!(
                "__instanceof__(&{}, &{})",
                a.first().cloned().unwrap_or_else(|| "Value::Undefined".into()),
                a.get(1).cloned().unwrap_or_else(|| "Value::Undefined".into())
            ),
            "__delete__" => format!("__delete__(&{})", a.first().cloned().unwrap_or_else(|| "Value::Undefined".into())),
            "__keys__" => format!("__keys__({})", a.first().cloned().unwrap_or_else(|| "Value::Undefined".into())),
            "__indices__" => {
                self.needs_indices = true;
                format!("Value::Array(__indices__({}))", a.first().cloned().unwrap_or_else(|| "Value::array(vec![])".into()))
            }
            "__new_array__" => "__map_new__()".to_string(),
            "__map_new__" => "__map_new__()".to_string(), // used by Go new array
            "Math_sqrt" | "sqrt" => format!("__sqrt__(&{})", a.first().cloned().unwrap_or_else(|| "Value::Int(0)".into())),
            "floor" => format!("__floor__(&{})", a.first().cloned().unwrap_or_else(|| "Value::Int(0)".into())),
            "ceil" => format!("__ceil__(&{})", a.first().cloned().unwrap_or_else(|| "Value::Int(0)".into())),
            "round" => format!("__round__(&{})", a.first().cloned().unwrap_or_else(|| "Value::Int(0)".into())),
            "notnull" | "__notnull__" => a.first().cloned().unwrap_or_else(|| "Value::Undefined".into()),
            _ => return None,
        })
    }

    /// static method calls like Math.max / Object.keys / console.log
    fn builtin_method_dynamic(&mut self, obj: &Expr, name: &str, args: &[Expr]) -> Option<String> {
        if let Expr::Ident(base) = obj {
            let a: Vec<String> = args.iter().map(|x| self.expr(x)).collect();
            match (base.as_str(), name) {
                ("Math", "sqrt") => return Some(format!("__sqrt__(&{})", a.first().cloned().unwrap_or_else(|| "Value::Int(0)".into()))),
                ("Math", "abs") => return Some(format!("__abs__(&{})", a.first().cloned().unwrap_or_else(|| "Value::Int(0)".into()))),
                ("Math", "floor") => return Some(format!("__floor__(&{})", a.first().cloned().unwrap_or_else(|| "Value::Int(0)".into()))),
                ("Math", "ceil") => return Some(format!("__ceil__(&{})", a.first().cloned().unwrap_or_else(|| "Value::Int(0)".into()))),
                ("Math", "round") => return Some(format!("__round__(&{})", a.first().cloned().unwrap_or_else(|| "Value::Int(0)".into()))),
                ("Math", "max") => return Some(format!("__max__(&[{}])", a.join(", "))),
                ("Math", "min") => return Some(format!("__min__(&[{}])", a.join(", "))),
                ("Math", "pow") => return Some(format!("Value::pow(&{}, &{})", a[0], a.get(1).cloned().unwrap_or_else(|| "Value::Int(0)".into()))),
                ("Object", "keys") => return Some(format!("__keys__({})", a.first().cloned().unwrap_or_else(|| "Value::Undefined".into()))),
                ("Object", "values") => return Some(format!("__values__({})", a.first().cloned().unwrap_or_else(|| "Value::Undefined".into()))),
                ("Object", "assign") => return Some(format!("__obj_assign__(&[{}])", a.join(", "))),
                ("Object", "freeze") => return Some(a.first().cloned().unwrap_or_else(|| "Value::Undefined".into())),
                ("Object", "entries") => return Some(format!("__entries_v__({})", a.first().cloned().unwrap_or_else(|| "Value::Undefined".into()))),
                ("console", "log") => return Some(format!("__print__(&[{}])", a.join(", "))),
                ("console", "error") | ("console", "warn") => return Some(format!("__print__(&[{}])", a.join(", "))),
                ("JSON", "stringify") => return Some(format!("__json_stringify__({})", a.first().cloned().unwrap_or_else(|| "Value::Undefined".into()))),
                ("String", "fromCharCode") => return Some(format!("Value::Str(char::from_u32({} as u32).map(|c| c.to_string()).unwrap_or_default())", a.first().cloned().unwrap_or_else(|| "Value::Int(0)".into()))),
                ("Array", "isArray") => return Some(format!("Value::Bool(matches!({}, Value::Array(_)))", a.first().cloned().unwrap_or_else(|| "Value::Undefined".into()))),
                ("Array", "from") => return Some(format!("__to_list__(&{})", a.first().cloned().unwrap_or_else(|| "Value::Undefined".into()))),
                ("Number", "parseInt") => return Some(format!("__to_int__(&{})", a.first().cloned().unwrap_or_else(|| "Value::Undefined".into()))),
                ("Number", "parseFloat") => return Some(format!("__to_float__(&{})", a.first().cloned().unwrap_or_else(|| "Value::Undefined".into()))),
                _ => {}
            }
        }
        None
    }

    fn cast_dynamic(&mut self, v: &str, ty: &Ty) -> String {
        match ty {
            Ty::Int | Ty::Long => format!("__to_int__(&{})", v),
            Ty::Float | Ty::Double => format!("__to_float__(&{})", v),
            Ty::Bool => format!("Value::Bool({}.truthy())", v),
            Ty::Str => format!("__to_str__(&{})", v),
            _ => v.to_string(),
        }
    }

    // ------------------------------------------------------------------
    // typed expressions
    // ------------------------------------------------------------------
    fn expr_typed(&mut self, e: &Expr, hint: &Ty) -> String {
        match e {
            Expr::Int(v) => match hint {
                Ty::Double | Ty::Float => format!("{}f64", v),
                _ => format!("{}i64", v),
            },
            Expr::Float(v) => format!("{}f64", v),
            Expr::Bool(b) => b.to_string(),
            Expr::Str(s) => format!("\"{}\".to_string()", rust_string_body(s)),
            Expr::Char(c) => format!("'{}'", c),
            Expr::Null | Expr::Undefined | Expr::Unit => {
                if matches!(hint, Ty::Option(_)) {
                    "None".into()
                } else {
                    "Default::default()".into()
                }
            }
            Expr::Ident(name) => self.ident_expr(name),
            Expr::This => "this.clone()".into(),
            Expr::Super => "this.clone()".into(),
            Expr::Paren(e) => self.expr_typed(e, hint),
            Expr::Binary { op, l, r } => {
                match op {
                    BinOp::And => format!("(({}) && ({}))", self.expr_typed(l, &Ty::Bool), self.expr_typed(r, &Ty::Bool)),
                    BinOp::Or => format!("(({}) || ({}))", self.expr_typed(l, &Ty::Bool), self.expr_typed(r, &Ty::Bool)),
                    _ => {
                        // any Value operand -> dynamic Value semantics
                        if self.is_val_expr(l) || self.is_val_expr(r) {
                            let lv = self.to_value(l);
                            let rv = self.to_value(r);
                            match op {
                                BinOp::Eq => format!(
                                    "Value::Bool(Value::eq(&{}, &{}))",
                                    lv, rv
                                ),
                                BinOp::Ne => format!(
                                    "Value::Bool(!Value::eq(&{}, &{}))",
                                    lv, rv
                                ),
                                BinOp::Lt => format!("Value::Bool(Value::lt(&{}, &{}))", lv, rv),
                                BinOp::Le => format!("Value::Bool(!Value::lt(&{}, &{}))", rv, lv),
                                BinOp::Gt => format!("Value::Bool(Value::lt(&{}, &{}))", rv, lv),
                                BinOp::Ge => format!("Value::Bool(!Value::lt(&{}, &{}))", lv, rv),
                                BinOp::In => format!(
                                    "Value::Bool(__contains__(&{}, &{}))",
                                    rv, lv
                                ),
                                _ => {
                                    let v = self.binop_value(*op, &lv, &rv);
                                    self.from_value(&v, hint)
                                }
                            }
                        } else if self.expr_is_string(l) || self.expr_is_string(r) {
                            if matches!(op, BinOp::Add) {
                                format!(
                                    "format!(\"{{}}{{}}\", {}, {})",
                                    self.expr_typed(l, &Ty::Str),
                                    self.expr_typed(r, &Ty::Str)
                                )
                            } else {
                                let ls = self.expr_typed(l, &Ty::Long);
                                let rs = self.expr_typed(r, &Ty::Long);
                                self.binop_typed(*op, &ls, &rs)
                            }
                        } else {
                            let ls = self.expr_typed(l, &Ty::Long);
                            let rs = self.expr_typed(r, &Ty::Long);
                            self.binop_typed(*op, &ls, &rs)
                        }
                    }
                }
            }
            Expr::Unary { op, e } => match op {
                UnOp::Not => format!("(!{})", self.expr_typed(e, &Ty::Bool)),
                UnOp::Neg => format!("(-{})", self.expr_typed(e, hint)),
                UnOp::BitNot => format!("(!{})", self.expr_typed(e, &Ty::Long)),
                UnOp::PreInc | UnOp::PreDec => match &**e {
                    Expr::Ident(n) => {
                        let id = rust_ident(n);
                        if self.is_val_expr(e) {
                            let one = if matches!(op, UnOp::PreInc) { "add" } else { "sub" };
                            let cur = format!("{}.borrow().clone()", id);
                            self.w(&format!(
                                "*{}.borrow_mut() = Value::{}(&{}, &Value::Int(1));",
                                id, one, cur
                            ));
                            return cur;
                        }
                        let delta = if matches!(op, UnOp::PreInc) { "+" } else { "-" };
                        self.w(&format!("{} {}= 1;", id, delta));
                        id
                    }
                    _ => "0".into(),
                },
            },
            Expr::Post { op, e } => match &**e {
                Expr::Ident(n) => {
                    let id = rust_ident(n);
                    if self.is_val_expr(e) {
                        let one = if matches!(op, UnOp::PreInc) { "add" } else { "sub" };
                        let cur = format!("{}.borrow().clone()", id);
                        self.w(&format!(
                            "*{}.borrow_mut() = Value::{}(&{}, &Value::Int(1));",
                            id, one, cur
                        ));
                        return cur;
                    }
                    let delta = if matches!(op, UnOp::PreInc) { "+" } else { "-" };
                    self.w(&format!("{} {}= 1;", id, delta));
                    id
                }
                _ => "0".into(),
            },
            Expr::Call { callee, args } => self.typed_call(callee, args),
            Expr::Method { obj, name, args, nullsafe } => {
                self.typed_method_call(obj, name, args, *nullsafe)
            }
            Expr::Field { obj, name, .. } => {
                let o = self.expr_typed(obj, &Ty::Any);
                if matches!(**obj, Expr::This) {
                    format!("this.borrow().{}.clone()", rust_ident(name))
                } else {
                    format!("{}.borrow().{}.clone()", o, rust_ident(name))
                }
            }
            Expr::Index { obj, idx } => {
                if self.is_val_expr(obj) {
                    let o = self.expr_typed(obj, &Ty::Any);
                    let iv = self.to_value(idx);
                    return format!("Value::index_get(&{}, &{})", o, iv);
                }
                let o = self.expr_typed(obj, &Ty::Any);
                let i = self.expr_typed(idx, &Ty::Long);
                format!("{}.borrow()[{} as usize].clone()", o, i)
            }
            Expr::Slice { obj, lo, hi } => {
                let o = self.expr_typed(obj, &Ty::Any);
                let lo = lo.as_ref().map(|e| self.expr_typed(e, &Ty::Long)).unwrap_or_else(|| "0".into());
                let hi = hi
                    .as_ref()
                    .map(|e| self.expr_typed(e, &Ty::Long))
                    .unwrap_or_else(|| format!("{}.borrow().len()", o));
                format!("rt({}.borrow()[{} as usize..{} as usize].to_vec())", o, lo, hi)
            }
            Expr::Array(items) => {
                let elems: Vec<String> = items
                    .iter()
                    .map(|it| self.expr_typed(it, &Ty::Any))
                    .collect();
                if hint.is_any() {
                    let vals: Vec<String> =
                        items.iter().map(|it| self.to_value(it)).collect();
                    format!("Value::array(vec![{}])", vals.join(", "))
                } else {
                    format!("rt(vec![{}])", elems.join(", "))
                }
            }
            Expr::Dict(pairs) => {
                let entries: Vec<String> = pairs
                    .iter()
                    .map(|(k, v)| format!("({}, {})", self.expr_typed(k, &Ty::Any), self.expr_typed(v, &Ty::Any)))
                    .collect();
                if hint.is_any() {
                    let vals: Vec<String> = pairs
                        .iter()
                        .map(|(k, v)| format!("({}, {})", self.to_value(k), self.to_value(v)))
                        .collect();
                    format!("__dict_new__(vec![{}])", vals.join(", "))
                } else {
                    format!("rt([{}].into_iter().collect())", entries.join(", "))
                }
            }
            Expr::Object(fields) => {
                // struct composite literal
                let class = self
                    .classes_order
                    .iter()
                    .find(|_| false)
                    .cloned();
                let _ = class;
                // determine struct name from context: unknown here; caller wraps
                let entries: Vec<String> = fields
                    .iter()
                    .map(|(k, v)| format!("{}: {}", rust_ident(k), self.expr_typed(v, &Ty::Any)))
                    .collect();
                // fallback: use first class with matching fields
                format!("__struct__!({}, {})", quote_fields(fields), entries.join(", "))
            }
            Expr::New { class, args } => {
                let cname = rust_type_name(class);
                let a: Vec<String> = args.iter().map(|x| self.expr_typed(x, &Ty::Any)).collect();
                let all_fields = self
                    .classes
                    .get(class)
                    .map(|c| self.all_fields(c))
                    .unwrap_or_default();
                if a.len() == all_fields.len() && !all_fields.is_empty() {
                    let sets: Vec<String> = all_fields
                        .iter()
                        .zip(a.iter())
                        .map(|((n, _), v)| format!("{}: {}.clone()", rust_ident(n), v))
                        .collect();
                    format!("rt({} {{ {} }})", cname, sets.join(", "))
                } else {
                    // named init via ctor if exists
                    if let Some(c) = self.classes.get(class) {
                        if c.ctor.is_some() {
                            return format!(
                                "rt({}_new({}))",
                                cname,
                                a.iter().map(|x| x.clone()).collect::<Vec<_>>().join(", ")
                            );
                        }
                    }
                    format!("rt({}::new())", cname)
                }
            }
            Expr::Closure { params, body, value } => {
                let params_s: Vec<String> = params
                    .iter()
                    .map(|p| format!("{}: {}", rust_ident(&p.name), self.ty(&p.ty)))
                    .collect();
                let mut inner = Gen {
                    module: self.module,
                    dynamic: self.dynamic,
                    out: String::new(),
                    indent: 0,
                    scope: Scope {
                        locals: params
                            .iter()
                            .map(|p| (p.name.clone(), p.ty.clone()))
                            .collect(),
                        in_closure: true,
                        params: params.iter().map(|p| p.name.clone()).collect(),
                        is_method: false,
                        is_ctor: false,
                        cell_locals: params.iter().map(|p| p.name.clone()).collect(),
                        class_of: None,
                        parent_of: None,
                        ret_ty: None,
                    },
                    globals: self.globals.clone(),
                    classes: self.classes.clone(),
                    classes_order: vec![],
                    functions: self.functions.clone(),
                    needs_indices: false,
                    needs_entries: false,
                    defer_stack: vec![],
                };
                match value {
                    Some(v) => {
                        let val = inner.expr_typed(v, &Ty::Any);
                        inner.w(&format!("{};", val));
                    }
                    None => {
                        inner.gen_block(body);
                    }
                }
                let code = std::mem::take(&mut inner.out);
                let body_code = code
                    .lines()
                    .map(|l| format!("    {}", l))
                    .collect::<Vec<_>>()
                    .join("\n");
                format!(
                    "|{}: Vec<{}>| {{\n{}\n}}",
                    params_s.join(", "),
                    self.ty(&Ty::Any),
                    body_code
                )
            }
            Expr::Ternary { cond, then, els } => format!(
                "(if {} {{ {} }} else {{ {} }})",
                self.expr_typed(cond, &Ty::Bool),
                self.expr_typed(then, hint),
                self.expr_typed(els, hint)
            ),
            Expr::Cast { e, ty } => {
                let v = self.expr_typed(e, ty);
                match ty {
                    Ty::Int | Ty::Long => format!("({} as i64)", v),
                    Ty::Double | Ty::Float => format!("({} as f64)", v),
                    Ty::Bool => format!("({} != 0)", v),
                    _ => v,
                }
            }
            Expr::Interp { parts } => {
                let mut fmtstr = String::new();
                let mut vals: Vec<String> = Vec::new();
                for p in parts {
                    match p {
                        InterpPart::Lit(s) => fmtstr.push_str(&rust_string_body(s)),
                        InterpPart::E(e) => {
                            fmtstr.push_str("{}");
                            vals.push(self.expr_typed(e, &Ty::Any));
                        }
                    }
                }
                format!("format!(\"{}\", {})", fmtstr, vals.join(", "))
            }
            Expr::Range { lo, hi, inclusive } => {
                let l = self.expr_typed(lo, &Ty::Long);
                let h = self.expr_typed(hi, &Ty::Long);
                if hint.is_any() {
                    if *inclusive {
                        format!(
                            "Value::Array(rt(({}..={}).map(|i| Value::Int(i)).collect::<Vec<Value>>()))",
                            l, h
                        )
                    } else {
                        format!(
                            "Value::Array(rt(({}..{}).map(|i| Value::Int(i)).collect::<Vec<Value>>()))",
                            l, h
                        )
                    }
                } else if *inclusive {
                    format!("rt(({}..={}).collect::<Vec<i64>>())", l, h)
                } else {
                    format!("rt(({}..{}).collect::<Vec<i64>>())", l, h)
                }
            }
            Expr::Named { name, e } => format!("{}: {}", rust_ident(name), self.expr_typed(e, &Ty::Any)),
            Expr::Spread(e) => self.expr_typed(e, &Ty::Any),
            Expr::Seq(items) => {
                let mut last = "Default::default()".to_string();
                for (i, it) in items.iter().enumerate() {
                    if i + 1 == items.len() {
                        last = self.expr_typed(it, &Ty::Any);
                    } else {
                        let v = self.expr_typed(it, &Ty::Any);
                        self.w(&format!("let _ = {};", v));
                    }
                }
                last
            }
            Expr::Await(e) => self.expr_typed(e, hint),
            Expr::AssignExpr { target, op, value } => {
                self.assign(target, *op, value);
                match &**value {
                    Expr::Ident(n) => self.ident_expr(n),
                    other => self.expr_typed(other, &Ty::Any),
                }
            }
            Expr::FuncRef(n) => rust_ident(n),
        }
    }

    fn expr_is_string(&self, e: &Expr) -> bool {
        matches!(e, Expr::Str(_) | Expr::Interp { .. })
            || matches!(e, Expr::Ident(n) if self
                .scope
                .locals
                .get(n)
                .map_or(false, |t| matches!(t, Ty::Str)))
    }

    fn typed_call(&mut self, callee: &Expr, args: &[Expr]) -> String {
        if let Expr::Ident(name) = callee {
            let a: Vec<String> = args.iter().map(|x| self.expr_typed(x, &Ty::Any)).collect();
            // Go two-value map lookup helper
            if name == "__map_has__" {
                if args.len() == 2 {
                    let m = self.to_value(&args[0]);
                    let k = self.to_value(&args[1]);
                    return format!("__map_has__(&{}, &{})", m, k);
                }
            }
            // Go builtins
            match name.as_str() {
                "len" => return format!("{}.borrow().len() as i64", a[0]),
                "cap" => return format!("{}.borrow().len() as i64", a[0]),
                "append" => {
                    // append(s, x) -> push and return
                    if a.len() == 2 {
                        return format!(
                            "{{ {}.borrow_mut().push({}); {}.clone() }}",
                            a[0], a[1], a[0]
                        );
                    }
                    return a[0].clone();
                }
                "make" => {
                    return "Default::default()".into();
                }
                "new" => return "Default::default()".into(),
                "delete" => {
                    return format!("{}.borrow_mut().remove(&{});", a[0], a[1]);
                }
                "copy" => return "0".into(),
                "panic" => {
                    return format!("panic!(\"{{}}\", {})", a.first().cloned().unwrap_or_else(|| "\"\".into()".into()));
                }
                "print" | "println" => {
                    return format!("println!(\"{{}}\", {})", a.join(", "));
                }
                "min" | "max" => {
                    return format!(
                        "{}.{}({})",
                        a[0],
                        if name == "min" { "min" } else { "max" },
                        a[1]
                    );
                }
                "abs" => return format!("{}.abs()", a[0]),
                _ => {}
            }
            if self.functions.contains(name) {
                return format!("{}({})", rust_ident(name), a.join(", "));
            }
            // struct composite literal: __structinit_Name(...)
            if let Some(cname) = name.strip_prefix("__structinit_") {
                let cname_id = rust_type_name(cname);
                let all_named =
                    !args.is_empty() && args.iter().all(|x| matches!(x, Expr::Named { .. }));
                if all_named {
                    let sets: Vec<String> = args
                        .iter()
                        .map(|x| match x {
                            Expr::Named { name, e } => format!(
                                "{}: {}",
                                rust_ident(name),
                                self.expr_typed(e, &Ty::Any)
                            ),
                            _ => unreachable!(),
                        })
                        .collect();
                    return format!("rt({} {{ {} }})", cname_id, sets.join(", "));
                }
                let c = self.classes.get(cname);
                let all_fields = c.map(|c| self.all_fields(c)).unwrap_or_default();
                let sets: Vec<String> = all_fields
                    .iter()
                    .zip(args.iter())
                    .map(|((n, _), v)| {
                        format!("{}: {}", rust_ident(n), self.expr_typed(v, &Ty::Any))
                    })
                    .collect();
                return format!("rt({} {{ {} }})", cname_id, sets.join(", "));
            }
            // class constructor call: Name(args)
            if self.classes.contains_key(name) {
                let cname = rust_type_name(name);
                let c = self.classes.get(name).unwrap();
                let all_fields = self.all_fields(c);
                let all_named =
                    !args.is_empty() && args.iter().all(|x| matches!(x, Expr::Named { .. }));
                if all_named {
                    let sets: Vec<String> = args
                        .iter()
                        .map(|x| match x {
                            Expr::Named { name, e } => format!(
                                "{}: {}",
                                rust_ident(name),
                                self.expr_typed(e, &Ty::Any)
                            ),
                            _ => unreachable!(),
                        })
                        .collect();
                    return format!("rt({} {{ {} }})", cname, sets.join(", "));
                }
                if !all_fields.is_empty() && args.len() <= all_fields.len() {
                    let sets: Vec<String> = all_fields
                        .iter()
                        .zip(args.iter())
                        .map(|((n, _), v)| {
                            format!("{}: {}", rust_ident(n), self.expr_typed(v, &Ty::Any))
                        })
                        .collect();
                    return format!("rt({} {{ {} }})", cname, sets.join(", "));
                }
                return format!("rt({}::new())", cname);
            }
            return format!("{}({})", rust_ident(name), a.join(", "));
        }
        let f = self.expr_typed(callee, &Ty::Any);
        let a: Vec<String> = args.iter().map(|x| self.expr_typed(x, &Ty::Any)).collect();
        format!("({})({})", f, a.join(", "))
    }

    fn typed_method_call(&mut self, obj: &Expr, name: &str, args: &[Expr], _nullsafe: bool) -> String {
        let a: Vec<String> = args.iter().map(|x| self.expr_typed(x, &Ty::Any)).collect();
        // known local class -> m_method(this, ...)
        if let Expr::Ident(base) = obj {
            if let Some(Ty::Class(cname)) = self.scope.locals.get(base).cloned() {
                if self.classes.contains_key(&cname) {
                    return format!(
                        "{}::m_{}(&{}, {})",
                        rust_type_name(&cname),
                        rust_ident(name),
                        rust_ident(base),
                        a.join(", ")
                    );
                }
            }
        }
        if matches!(obj, Expr::This) {
            // this.method() -> Class::m_method(&this, ...)
            return format!("__this_method__({}, {})", name, a.join(", "));
        }
        // string / array / map built-in methods
        let o = self.expr_typed(obj, &Ty::Any);
        match name {
            "length" | "len" | "size" => format!("{}.borrow().len()", o),
            "push" | "append" | "add" => format!("{{ {}.borrow_mut().push({}); }}", o, a.first().cloned().unwrap_or_else(|| "Default::default()".into())),
            "pop" => format!("{}.borrow_mut().pop().unwrap_or_default()", o),
            "isEmpty" | "empty" | "is_empty" => format!("{}.borrow().is_empty()", o),
            "contains" | "includes" => format!("{}.borrow().contains(&{})", o, a.first().cloned().unwrap_or_else(|| "Default::default()".into())),
            "get" => format!(
                "{}.borrow().get(&{}).cloned().unwrap_or_default()",
                o,
                a.first().cloned().unwrap_or_else(|| "Default::default()".into())
            ),
            "set" | "__setitem__" | "put" => format!(
                "{{ {}.borrow_mut().insert({}, {}); }}",
                o,
                a.first().cloned().unwrap_or_else(|| "Default::default()".into()),
                a.get(1).cloned().unwrap_or_else(|| "Default::default()".into())
            ),
            "join" => format!("{}.borrow().join(&{})", o, a.first().cloned().unwrap_or_else(|| "\"\".to_string()".into())),
            "substring" | "slice" => format!(
                "{}.borrow()[{} as usize..{} as usize].to_string()",
                o,
                a.first().cloned().unwrap_or_else(|| "0".into()),
                a.get(1).cloned().unwrap_or_else(|| "0".into())
            ),
            "to_string" | "toString" => format!("format!(\"{{:?}}\", {})", o),
            "keys" => format!("rt({}.borrow().keys().cloned().collect::<Vec<_>>())", o),
            "values" => format!("rt({}.borrow().values().cloned().collect::<Vec<_>>())", o),
            _ => format!("unimplemented!(\"method {} (unknown type)\")", name),
        }
    }

    fn ty(&self, t: &Ty) -> String {
        match t {
            Ty::Any | Ty::Named(_) => "Value".into(),
            Ty::Int => "i64".into(),
            Ty::Long => "i64".into(),
            Ty::Float | Ty::Double => "f64".into(),
            Ty::Bool => "bool".into(),
            Ty::Char => "char".into(),
            Ty::Str => "String".into(),
            Ty::Void => "()".into(),
            Ty::Array(el) => format!("Rt<Vec<{}>>", self.ty(el)),
            Ty::Map(k, v) => format!("Rt<std::collections::HashMap<{}, {}>>", self.ty(k), self.ty(v)),
            Ty::Option(inner) => format!("Option<{}>", self.ty(inner)),
            Ty::Class(name) => format!("Rt<{}>", rust_type_name(name)),
            Ty::Func { .. } => "Value".into(),
        }
    }
}

fn default_value(t: &Ty) -> String {
    match t {
        Ty::Any | Ty::Named(_) => "Value::Undefined".into(),
        Ty::Int => "0i64".into(),
        Ty::Long => "0i64".into(),
        Ty::Float | Ty::Double => "0.0f64".into(),
        Ty::Bool => "false".into(),
        Ty::Char => "'\\0'".into(),
        Ty::Str => "String::new()".into(),
        Ty::Void => "()".into(),
        Ty::Array(el) => format!("rt(Vec::<{}>::new())", default_inner(el)),
        Ty::Map(k, v) => format!(
            "rt(std::collections::HashMap::<{}, {}>::new())",
            default_inner(k),
            default_inner(v)
        ),
        Ty::Option(_) => "None".into(),
        Ty::Class(name) => format!("rt({}::new())", rust_type_name(name)),
        Ty::Func { .. } => "Value::Undefined".into(),
    }
}

fn default_inner(t: &Ty) -> String {
    match t {
        Ty::Any => "Value".into(),
        Ty::Int => "i64".into(),
        Ty::Long => "i64".into(),
        Ty::Float | Ty::Double => "f64".into(),
        Ty::Bool => "bool".into(),
        Ty::Char => "char".into(),
        Ty::Str => "String".into(),
        Ty::Void => "()".into(),
        Ty::Array(el) => format!("Rt<Vec<{}>>", default_inner(el)),
        Ty::Map(k, v) => format!(
            "Rt<std::collections::HashMap<{}, {}>>",
            default_inner(k),
            default_inner(v)
        ),
        Ty::Option(inner) => format!("Option<{}>", default_inner(inner)),
        Ty::Class(name) => format!("Rt<{}>", rust_type_name(name)),
        Ty::Func { .. } => "Value".into(),
        Ty::Named(_) => "Value".into(),
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum VKind {
    Val,
    Ref,
    Prim,
    Int,
    Float,
    Bool,
    Str,
    Unknown,
}

fn obj_str(o: &str) -> String {
    o.to_string()
}

fn inner_param_index(params: &[Param], name: &str) -> usize {
    params.iter().position(|p| p.name == name).unwrap_or(0)
}

fn quote_fields(fields: &[(String, Expr)]) -> String {
    fields
        .iter()
        .map(|(k, _)| format!("\"{}\"", k))
        .collect::<Vec<_>>()
        .join(", ")
}
