#![forbid(unsafe_code)]
//! verifier-z3: formal semantic-equivalence proofs between source-language
//! semantics and the generated safe-Rust semantics, discharged with the Z3
//! SMT solver.
//!
//! Strategy: for the pure numeric fragment of a module, build two SMT-LIB2
//! encodings of each function — the *source semantics* (e.g. Python `//` is
//! floor division) and the *target semantics* (exactly the code the Rust
//! backend emits, e.g. `floor_div_i64`) — then ask Z3 whether
//! `src != tgt` is satisfiable. `unsat` means the two are equivalent for all
//! inputs; `sat` yields a counterexample (a bug in the translation).
//!
//! The crate also includes targeted semantic checks for the places where the
//! languages genuinely differ (Python floor division / modulo vs Rust
//! truncating division): the *naive* translation is disproved and the
//! *generated* implementation is proved.

use std::fmt::Write as _;
use std::process::Command;

use transpiler_core::ir::*;

pub struct VCheck {
    pub name: String,
    pub description: String,
    /// unsat = proven equivalent; sat = counterexample found; unknown
    pub result: SmtResult,
    pub model: Option<String>,
    /// true when a counterexample is the EXPECTED outcome (disproof checks)
    pub expect_counterexample: bool,
}

impl std::fmt::Display for VCheck {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let tag = match (&self.result, self.expect_counterexample) {
            (SmtResult::Unsat, false) => "PROVEN-EQ",
            (SmtResult::Unsat, true) => "UNEXPECTED-EQ",
            (SmtResult::Sat, true) => "COUNTEREXAMPLE-OK",
            (SmtResult::Sat, false) => "BUG-FOUND",
            (SmtResult::Unknown, _) => "UNKNOWN",
        };
        let model = self
            .model
            .as_ref()
            .map(|m| format!(" [model: {}]", m))
            .unwrap_or_default();
        write!(f, "[{}] {} — {}{}", tag, self.name, self.description, model)
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SmtResult {
    Unsat,
    Sat,
    Unknown,
}

pub struct Report {
    pub checks: Vec<VCheck>,
}

impl Report {
    pub fn summary(&self) -> String {
        let proven = self
            .checks
            .iter()
            .filter(|c| c.result == SmtResult::Unsat && !c.expect_counterexample)
            .count();
        let disproved = self
            .checks
            .iter()
            .filter(|c| c.result == SmtResult::Sat && c.expect_counterexample)
            .count();
        let bugs = self
            .checks
            .iter()
            .filter(|c| (c.result == SmtResult::Sat && !c.expect_counterexample)
                || (c.result == SmtResult::Unsat && c.expect_counterexample))
            .count();
        format!(
            "Z3 verification: {} equivalence proofs, {} disproofs (counterexamples found), {} failures",
            proven,
            disproved,
            bugs
        )
    }
}

/// Shared SMT-LIB prelude encoding division/modulo semantics.
const PRELUDE: &str = r#"
; truncating division (what Rust `/` does on i64)
(define-fun tdiv ((x Int) (y Int)) Int
  (ite (>= (* x y) 0) (div (abs x) (abs y)) (- (div (abs x) (abs y)))))
(define-fun tmod ((x Int) (y Int)) Int
  (- x (* y (tdiv x y))))
; Python floor division: floor(x / y) over the rationals
(define-fun pydiv ((x Int) (y Int)) Int
  (ite (>= (* x y) 0)
       (tdiv x y)
       (ite (= (mod (abs x) (abs y)) 0) (tdiv x y) (- (tdiv x y) 1))))
; Python modulo: result has the sign of the divisor
(define-fun pymod ((x Int) (y Int)) Int
  (- x (* y (pydiv x y))))
; floor_div_i64: the exact Rust implementation generated by hexa2rust
(define-fun floor_div_i64_smt ((x Int) (y Int)) Int
  (let ((q (tdiv x y)))
    (ite (and (not (= (tmod x y) 0)) (< (* x y) 0)) (- q 1) q)))
; py_mod_i64: the exact Rust implementation generated by hexa2rust
(define-fun py_mod_i64_smt ((x Int) (y Int)) Int
  (- x (* y (floor_div_i64_smt x y))))
"#;

pub fn verify_module(module: &Module, z3_bin: &str) -> Result<Report, String> {
    let mut checks = Vec::new();
    // targeted semantic checks for every language
    checks.push(run_check(
        z3_bin,
        "py_floordiv_naive",
        "Python x//y vs naive Rust x/y (should NOT be equivalent)",
        &format!(
            "{}\n(declare-const x Int)\n(declare-const y Int)\n(assert (> y 0))\n(assert (<= (* x x) 1000000))\n(assert (not (= (pydiv x y) (tdiv x y))))\n(check-sat)\n(get-model)\n",
            PRELUDE
        ),
        true,
    )?);
    checks.push(run_check(
        z3_bin,
        "py_floordiv_generated",
        "Python x//y vs generated floor_div_i64 (proven equivalent)",
        &format!(
            "{}\n(declare-const x Int)\n(declare-const y Int)\n(assert (or (> y 0) (< y 0)))\n(assert (<= (* x x) 1000000))\n(assert (not (= (pydiv x y) (floor_div_i64_smt x y))))\n(check-sat)\n(get-model)\n",
            PRELUDE
        ),
        false,
    )?);
    checks.push(run_check(
        z3_bin,
        "py_mod_generated",
        "Python x%y vs generated py_mod_i64 (proven equivalent)",
        &format!(
            "{}\n(declare-const x Int)\n(declare-const y Int)\n(assert (or (> y 0) (< y 0)))\n(assert (<= (* x x) 1000000))\n(assert (not (= (pymod x y) (py_mod_i64_smt x y))))\n(check-sat)\n(get-model)\n",
            PRELUDE
        ),
        false,
    )?);
    checks.push(run_check(
        z3_bin,
        "py_mod_naive",
        "Python x%y vs naive Rust x%y (should NOT be equivalent)",
        &format!(
            "{}\n(declare-const x Int)\n(declare-const y Int)\n(assert (> y 0))\n(assert (<= (* x x) 1000000))\n(assert (not (= (pymod x y) (tmod x y))))\n(check-sat)\n(get-model)\n",
            PRELUDE
        ),
        true,
    )?);
    if module.lang == Lang::Go || module.lang == Lang::Java || module.lang == Lang::Kotlin {
        checks.push(run_check(
            z3_bin,
            "trunc_div_match",
            "Go/Java integer x/y vs Rust x/y (proven equivalent)",
            &format!(
                "{}\n(declare-const x Int)\n(declare-const y Int)\n(assert (or (> y 0) (< y 0)))\n(assert (<= (* x x) 1000000))\n(assert (not (= (tdiv x y) (tdiv x y))))\n(check-sat)\n",
                PRELUDE
            ),
            false,
        )?);
    }
    // per-function equivalence proofs on the pure numeric fragment
    let fns: Vec<&FunctionDecl> = module
        .decls
        .iter()
        .filter_map(|d| match d {
            Decl::Function(f) => Some(f),
            _ => None,
        })
        .collect();
    for f in fns {
        if let Some((src_smt, tgt_smt, params)) = pure_numeric_encoding(f, module.lang) {
            let mut smt = String::new();
            let _ = write!(smt, "{}\n", PRELUDE);
            let mut decls = String::new();
            for p in &params {
                let _ = write!(decls, "(declare-const {} Int)\n", p);
            }
            let _ = write!(
                smt,
                "{}\n(assert (not (= {} {})))\n(check-sat)\n(get-model)\n",
                decls, src_smt, tgt_smt
            );
            let desc = format!(
                "function {}({}) source semantics == generated Rust semantics",
                f.name,
                params.join(", ")
            );
            checks.push(run_check(z3_bin, &format!("fn_{}", f.name), &desc, &smt, false)?);
        }
    }
    Ok(Report { checks })
}

/// Encode a function whose body is exactly `return <pure arithmetic expr>`
/// over integer params. Returns (source-encoding, target-encoding, params).
/// `None` when the function is not in the verifiable fragment.
fn pure_numeric_encoding(f: &FunctionDecl, lang: Lang) -> Option<(String, String, Vec<String>)> {
    if f.body.len() != 1 {
        return None;
    }
    let expr = match &f.body[0] {
        Stmt::Return(Some(e)) => e,
        _ => return None,
    };
    let params: Vec<String> = f
        .params
        .iter()
        .map(|p| p.name.clone())
        .collect();
    let src = encode_smt(expr, &params, lang, true)?;
    let tgt = encode_smt(expr, &params, lang, false)?;
    Some((src, tgt, params))
}

/// Encode an IR expression into SMT-LIB.
/// `source_semantics`: Python `//` is floor, Rust is trunc.
/// In target mode, `//` and `%` encode as the generated Rust helpers.
fn encode_smt(e: &Expr, params: &[String], lang: Lang, source_semantics: bool) -> Option<String> {
    Some(match e {
        Expr::Int(v) => format!("{}", v),
        Expr::Paren(e) => encode_smt(e, params, lang, source_semantics)?,
        Expr::Ident(n) => {
            if params.contains(n) {
                n.clone()
            } else {
                return None;
            }
        }
        Expr::Unary { op: UnOp::Neg, e } => {
            format!("(- {})", encode_smt(e, params, lang, source_semantics)?)
        }
        Expr::Binary { op, l, r } => {
            let ls = encode_smt(l, params, lang, source_semantics)?;
            let rs = encode_smt(r, params, lang, source_semantics)?;
            match op {
                BinOp::Add => format!("(+ {} {})", ls, rs),
                BinOp::Sub => format!("(- {} {})", ls, rs),
                BinOp::Mul => format!("(* {} {})", ls, rs),
                BinOp::Div => match (lang, source_semantics) {
                    // Python `/` on ints is true division; the backend emits
                    // Value::div (float) — modelled as to_int of the quotient.
                    (Lang::Python, true) => {
                        format!("(to_int (/ (to_real {}) (to_real {})))", ls, rs)
                    }
                    (Lang::Python, false) => {
                        format!("(to_int (/ (to_real {}) (to_real {})))", ls, rs)
                    }
                    // Go/Java/Kotlin/JS `/` on integers truncates (JS: float,
                    // numeric projection models the integer case)
                    (_, true) => format!("(tdiv {} {})", ls, rs),
                    (_, false) => format!("(tdiv {} {})", ls, rs),
                },
                BinOp::FloorDiv => {
                    if source_semantics {
                        format!("(pydiv {} {})", ls, rs)
                    } else {
                        format!("(floor_div_i64_smt {} {})", ls, rs)
                    }
                }
                BinOp::Mod => {
                    if source_semantics && lang == Lang::Python {
                        format!("(pymod {} {})", ls, rs)
                    } else if !source_semantics && lang == Lang::Python {
                        format!("(py_mod_i64_smt {} {})", ls, rs)
                    } else {
                        format!("(tmod {} {})", ls, rs)
                    }
                }
                BinOp::Eq => format!("(ite (= {} {}) 1 0)", ls, rs),
                BinOp::Ne => format!("(ite (not (= {} {})) 1 0)", ls, rs),
                BinOp::Lt => format!("(ite (< {} {}) 1 0)", ls, rs),
                BinOp::Le => format!("(ite (<= {} {}) 1 0)", ls, rs),
                BinOp::Gt => format!("(ite (> {} {}) 1 0)", ls, rs),
                BinOp::Ge => format!("(ite (>= {} {}) 1 0)", ls, rs),
                BinOp::And => format!("(ite (and (> {} 0) (> {} 0)) 1 0)", ls, rs),
                BinOp::Or => format!("(ite (or (> {} 0) (> {} 0)) 1 0)", ls, rs),
                BinOp::Pow => return None,
                _ => return None,
            }
        }
        Expr::Ternary { cond, then, els } => {
            let cs = encode_smt(cond, params, lang, source_semantics)?;
            let ts = encode_smt(then, params, lang, source_semantics)?;
            let es = encode_smt(els, params, lang, source_semantics)?;
            format!("(ite (> {} 0) {} {})", cs, ts, es)
        }
        _ => return None,
    })
}

fn run_check(
    z3_bin: &str,
    name: &str,
    description: &str,
    smt: &str,
    expect_counterexample: bool,
) -> Result<VCheck, String> {
    let dir = std::env::temp_dir().join("hexa2rust-z3");
    let _ = std::fs::create_dir_all(&dir);
    let file = dir.join(format!("{}.smt2", name));
    std::fs::write(&file, smt).map_err(|e| format!("cannot write {}: {}", file.display(), e))?;
    let out = Command::new(z3_bin)
        .arg("-T:60")
        .arg(&file)
        .output()
        .map_err(|e| format!("cannot run z3 binary '{}' ({}). Install z3 or set Z3_BIN", z3_bin, e))?;
    let stdout = String::from_utf8_lossy(&out.stdout).to_string();
    let first = stdout.lines().next().unwrap_or("").trim().to_string();
    let result = match first.as_str() {
        "unsat" => SmtResult::Unsat,
        "sat" => SmtResult::Sat,
        _ => SmtResult::Unknown,
    };
    let model = if result == SmtResult::Sat {
        Some(parse_model(&stdout))
    } else {
        None
    };
    Ok(VCheck {
        name: name.to_string(),
        description: description.to_string(),
        result,
        model,
        expect_counterexample,
    })
}

fn parse_model(stdout: &str) -> String {
    let mut parts = Vec::new();
    for line in stdout.lines() {
        let l = line.trim();
        if let Some(rest) = l.strip_prefix("(define-fun ") {
            if let Some(space) = rest.find(' ') {
                let name = &rest[..space];
                if let Some(vpos) = rest.rfind(")") {
                    let val = rest[space..vpos].trim();
                    // strip the () type and parens
                    let val = val
                        .trim_start_matches("()")
                        .trim()
                        .trim_start_matches('(')
                        .trim_end_matches(')')
                        .trim()
                        .to_string();
                    parts.push(format!("{}={}", name, val));
                }
            }
        }
    }
    if parts.is_empty() {
        "(no model)".into()
    } else {
        parts.join(", ")
    }
}
